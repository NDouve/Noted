  // ---- copy: a sync client's conflict copy appears ----------------------------

  Future<void> _opCopy() async {
    final id = _pickPage();
    final m = model[id]!;
    var variant = _pick([
      'plain',
      'plain',
      'replacedMidMerge',
      'originalChanged',
      'stealPublish',
      'scan',
    ]);
    // Half the plain ones have the old file put back after the merge (run
    // 2026-11-16-01), picked by a generator of their own so the sequences of
    // the other steps stay the ones they were.
    if (variant == 'plain' && _crng.nextBool()) {
      variant = _crng.nextBool() ? 'revertedAfterVerify' : 'revertedRestart';
    }
    trace.add('conflict copy of ${_short(id)} in ${m.loc}: $variant');
    _kind = 'conflict:$variant';
    // The merge hooks belong to the closed-page merge: close the page.
    if (variant == 'replacedMidMerge' || variant == 'originalChanged') {
      await nb.open(_pickPage(where: (i, p) => i != id));
    }
    // A reverted page that is open would take the old file in at its next
    // save, and the re-check waits for it to close: another page is opened
    // (the first the model lists, so the main generator is not drawn from).
    if (variant.startsWith('reverted')) await nb.open(model.keys.firstWhere((i) => i != id));
    final disk = _disk(id);
    final z = _newBox(_text('copy'));
    final path = '${dirs[m.loc]!.path}$sep$id-DESKTOP-${++_copyCounter}.canvas';
    if (variant == 'stealPublish') {
      if (m.boxes.isEmpty) {
        _kind = null;
        return;
      }
      // R-3 as it happens in a run: the copy and the other device's newer file
      // both lack a box the original has, and the other device's file lands at
      // the publish. The original's own box must survive.
      await nb.open(_pickPage(where: (i, p) => i != id));
      final a = m.boxes.keys.elementAt(rng.nextInt(m.boxes.length));
      final without = disk.removeNode(a);
      final w = _newBox(_text('newer'));
      File(path).writeAsStringSync(writePage(without.insertNode(z)));
      storeOf(m.loc).beforePublishOnce = () => _externalWriteSync(id, without.insertNode(w));
      await nb.checkFile(path);
      await _settle();
      m.boxes[z.id] = _val(z);
      m.boxes[w.id] = _val(w);
      return;
    }
    File(path).writeAsStringSync(writePage(disk.insertNode(z)));
    m.boxes[z.id] = _val(z);
    switch (variant) {
      case 'plain':
        await nb.checkFile(path);
      case 'scan':
        await nb.checkFolders();
      case 'replacedMidMerge':
        // The provider replaces the copy with a newer one while it is merged.
        final later = _newBox(_text('later'));
        var fired = false;
        nb.syncHook = (point, p) async {
          if (point != 'copy-merged' || fired) return;
          fired = true;
          File(path).writeAsStringSync(writePage(disk.insertNode(z).insertNode(later)));
        };
        await nb.checkFile(path);
        nb.syncHook = null;
        expect(fired, isTrue);
        m.boxes[later.id] = _val(later);
      case 'originalChanged':
        // The other device's edit lands on the original after it was read.
        final newer = _newBox(_text('newer'));
        var fired = false;
        nb.syncHook = (point, p) async {
          if (point != 'original-read' || fired) return;
          fired = true;
          await _busyRetry(() => PageStore(dirs[m.loc]!).save(disk.insertNode(newer)));
        };
        await nb.checkFile(path);
        nb.syncHook = null;
        expect(fired, isTrue);
        m.boxes[newer.id] = _val(newer);
      case 'revertedAfterVerify':
      case 'revertedRestart':
        await _copyReverted(id, path, disk, z, restart: variant == 'revertedRestart');
    }
  }

  // R-1 (run 2026-11-16-01): the copy at [path] (the page [id] as [disk], plus
  // [z]) is merged, and once the merge is verified a sync client puts back the
  // file it fetched before. The copy is deleted all the same; recovery keeps
  // it, and its merge is done again by the re-check, or, with [restart] (no
  // re-check), by the replay at the next start. The page is closed.
  Future<void> _copyReverted(String id, String path, NotedPage disk, BoxRecord z, {required bool restart}) async {
    var fired = false;
    nb.syncHook = (point, p) async {
      if (point != 'copy-merged' || fired) return;
      fired = true;
      _externalWriteSync(id, disk);
    };
    await nb.checkFile(path);
    nb.syncHook = null;
    expect(fired, isTrue);
    expect(File(path).existsSync(), isFalse, reason: 'the copy is deleted');
    expect(_disk(id).node(z.id), isNull, reason: 'the old file is back');
    if (restart) {
      final kind = _kind;
      await _opRestart();
      _kind = kind;
    } else {
      await nb.recheckConsumedCopiesForTest();
      expect(_disk(id).node(z.id), isNotNull, reason: 'the re-check merged the kept copy again');
    }
  }

  /// The step `conflict:reverted*` after step [n]: a conflict copy of a page
  /// picked by its own generator, merged, and the old file put back after the
  /// merge (with [_opCopy]'s plain draws this reaches too few sequences).
  Future<void> _revertedCopyStep(int n) async {
    if (model.length < 2) return;
    final ids = model.keys.toList();
    final id = ids[_crng.nextInt(ids.length)];
    final m = model[id]!;
    final restart = _crng.nextBool();
    final kind = 'conflict:${restart ? 'revertedRestart' : 'revertedAfterVerify'}';
    trace.add('$kind on ${_short(id)} in ${m.loc}');
    _kind = kind;
    await nb.open(ids.firstWhere((i) => i != id));
    final disk = _disk(id);
    final z = _newBox(_text('copy'));
    final path = '${dirs[m.loc]!.path}$sep$id-DESKTOP-${++_copyCounter}.canvas';
    File(path).writeAsStringSync(writePage(disk.insertNode(z)));
    m.boxes[z.id] = _val(z);
    await _copyReverted(id, path, disk, z, restart: restart);
    trace.add('  ($kind done)');
    await _settle();
    await verify('step $n ($kind)');
    kinds.add(kind);
    _kind = null;
  }

  // ---- rename: a closed page is saved, sometimes raced ------------------------

  Future<void> _opRename() async {
    final id = _pickPage();
    final m = model[id]!;
    final variant = _pick(['plain', 'syncAtPublish', 'syncBeforeWrite']);
    trace.add('rename ${_short(id)} in ${m.loc}: $variant');
    _kind = 'rename:$variant';
    // Close it: open another page.
    if (model.length > 1) await nb.open(_pickPage(where: (i, p) => i != id));
    final st = storeOf(m.loc);
    final title = 'Title ${++_titleCounter}';
    if (variant != 'plain') {
      final y = _newBox(_text('sync'));
      final base = _disk(id);
      var fired = false;
      void hook() {
        fired = true;
        _externalWriteSync(id, base.insertNode(y));
      }

      if (variant == 'syncAtPublish') {
        st.beforePublishOnce = hook;
      } else {
        st.beforeWrite = hook;
      }
      await nb.rename(id, title);
      expect(fired, isTrue);
      m.boxes[y.id] = _val(y);
    } else {
      await nb.rename(id, title);
    }
    m.title = title;
  }

  // ---- move -------------------------------------------------------------------

  List<String> _subtree(String id) {
    final out = [id];
    for (final e in model.entries) {
      if (e.value.parent == id && e.value.loc == model[id]!.loc) out.addAll(_subtree(e.key));
    }
    return out;
  }

  Future<bool> _moveTo(String id, String to) {
    final from = model[id]!.loc;
    return switch (to) {
      'a' => nb.moveToLocation(id, binderPath: pathA),
      'b' => nb.moveToLocation(id, binderPath: pathB),
      'x' => nb.moveToFolder(id, dirs['x']!.path),
      _ => from == 'x' ? nb.moveToFolder(id, dirs['pages']!.path) : nb.moveToLocation(id),
    };
  }

  // At the [n]th rename of a move (`move-before-rename`, once per page, in
  // order), runs [act]; the page is renamed after it. [after] runs when the
  // hook has fired and is cleared.
  void Function() _atRename(int n, void Function() act) {
    final prev = nb.syncHook;
    var calls = 0;
    var fired = false;
    nb.syncHook = (point, path) async {
      await prev?.call(point, path);
      if (point != 'move-before-rename') return;
      if (++calls == n) {
        fired = true;
        act();
      }
    };
    return () {
      nb.syncHook = prev;
      if (!fired) trace.add('  (the move was refused before rename number $n)');
    };
  }

  // A file in [loc] under page [id]'s name: the name is taken there, as when
  // sync has put another file in its place. Returns the file, for its removal.
  File _takeName(String loc, String id) {
    final f = File('${dirs[loc]!.path}$sep$id.canvas');
    f.writeAsStringSync('taken');
    return f;
  }

  Future<void> _opMove() async {
    final variant = _pick([
      'plain',
      'plain',
      'plain',
      'pendingEdit',
      'failDestination',
      'failDestination',
      'syncAtSource',
    ]);
    // A fault on the last page of a subtree is the one that needs a rollback.
    final parents = [
      for (final e in model.entries)
        if (e.value.parent != null) e.value.parent!,
    ];
    final fails = variant == 'failDestination';
    final id = fails && parents.isNotEmpty ? parents[rng.nextInt(parents.length)] : _pickPage();
    final m = model[id]!;
    final to = _pick(_locs.where((l) => l != m.loc).toList());
    trace.add('move ${_short(id)} ${m.loc} -> $to: $variant');
    _kind = 'move:$variant';
    final subtree = _subtree(id);
    if (_standaloneLeft(subtree, to: to) < 1) {
      _kind = null;
      return; // a notebook always keeps a standalone page
    }
    // Some moves are by copy (a generator of its own, so the choices of the steps
    // stay the ones they were).
    if (variant == 'plain' && subtree.every((p) => model[p]!.assetText == null) && _kcrng.nextInt(3) == 0) {
      final copyVariant = const [
        'copyKeepsOriginal',
        'copyCrash',
        'deleteOriginalCopyChanged',
        'deleteOriginalCrash',
      ][_kcrng.nextInt(4)];
      _kind = 'move:$copyVariant';
      trace.add('  by copy: $copyVariant');
      await _opMoveCopy(copyVariant, id, to, subtree);
      return;
    }
    var mustFail = false;
    void Function()? restoreHook;
    File? taken;
    switch (variant) {
      case 'pendingEdit':
        // An edit not saved yet goes with the page.
        await nb.open(id);
        _localEdit(m, nb.current!);
      case 'failDestination':
        // The last page's name is taken at the target when its turn comes: the
        // move fails there, and the pages renamed before it go back.
        restoreHook = _atRename(subtree.length, () => taken = _takeName(to, subtree.last));
        mustFail = true;
      case 'syncAtSource':
        // A newer version lands on the source after the move checked it and
        // before its page is renamed: the page moves as it is, and is read at
        // the target.
        final y = _newBox(_text('sync'));
        await nb.flush();
        final base = _disk(id);
        restoreHook = _atRename(1, () => _externalWriteSync(id, base.insertNode(y)));
        m.boxes[y.id] = _val(y);
    }
    Object? error;
    var moved = false;
    try {
      moved = await _moveTo(id, to);
    } on Object catch (e) {
      error = e;
    }
    restoreHook?.call();
    if (taken != null && taken!.existsSync()) {
      taken!.deleteSync();
      await nb.checkFile(taken!.path);
      await nb.checkFolders();
    }
    if (mustFail) {
      expect(error, isNotNull, reason: 'the move should have been refused');
      return; // everything stays where it was
    }
    expect(error, isNull, reason: 'the move failed: $error');
    expect(moved, isTrue);
    for (final p in subtree) {
      model[p]!.loc = to;
    }
    m.parent = null;
  }

  // ---- a move by copy (a page kept in both places) ------------------------------

  /// After a copy-path move, or a crash in it or in Delete the original: which
  /// file of each page of [subtree] the notebook lists as the page and which, if
  /// both are there, as its duplicate. Sets the model's places and [_dups].
  void _readBoth(List<String> subtree, String from, String to) {
    _dups.clear();
    final listedDup = {
      for (final u in [...nb.unreadable, for (final b in nb.binders) ...b.unreadable])
        if (u.reason.startsWith('duplicate page id')) _norm(u.path),
    };
    for (final p in subtree) {
      final atFrom = File(_pathOf(p, from)).existsSync();
      final atTo = File(_pathOf(p, to)).existsSync();
      expect(atFrom || atTo, isTrue, reason: 'page ${_short(p)} is in neither place');
      var winner = atTo ? to : from;
      if (atFrom && atTo) {
        final fromDup = listedDup.contains(_norm(_pathOf(p, from)));
        final toDup = listedDup.contains(_norm(_pathOf(p, to)));
        expect(fromDup != toDup, isTrue, reason: 'exactly one of the two files of ${_short(p)} is listed as the duplicate');
        winner = fromDup ? to : from;
        final dupLoc = fromDup ? from : to;
        _dups.add(_Dup(p, dupLoc, _pathOf(p, dupLoc), File(_pathOf(p, dupLoc)).readAsStringSync()));
      }
      model[p]!.loc = winner;
    }
    // The copy was put at the top level of its place; an original keeps its parent.
    final root = subtree.first;
    model[root]!.parent = _disk(root).meta.parentId;
  }

  /// The user's removal of what a step left in both places.
  Future<void> _removeDups() async {
    for (final d in _dups) {
      File(d.path).deleteSync();
      await nb.checkFile(d.path);
    }
    _dups.clear();
    await nb.checkFolders();
  }

  Future<void> _restartAfterCrash() async {
    nb = _make();
    _spare.add(nb);
    await nb.load();
  }

  /// A move that can't rename: the pages are copied, the originals kept as
  /// duplicates, and the step ends in what [variant] says (see `_expectedKinds`).
  Future<void> _opMoveCopy(String variant, String id, String to, List<String> subtree) async {
    final from = model[id]!.loc;
    await nb.flush();
    final crashAtCopy = variant == 'copyCrash';
    var rekeyed = 0;
    if (crashAtCopy) {
      // The second `move-rekeyed` is after every copy was written.
      nb.syncHook = (point, _) async {
        if (point != 'move-rekeyed' || ++rekeyed < 2) return;
        _gone.add(nb);
        nb.dispose();
        throw StateError('crash after the copy');
      };
    }
    CopiedMove? kept;
    Object? error;
    Notebook.forceCopyMoveForTest = true;
    try {
      await _moveTo(id, to);
    } on OriginalsKeptException catch (e) {
      kept = e.move;
      error = e;
    } on Object catch (e) {
      error = e;
    } finally {
      Notebook.forceCopyMoveForTest = false;
    }
    if (crashAtCopy) {
      expect(error, isNotNull, reason: 'the process died in the copy');
      await _restartAfterCrash();
      // Every copy was written and nothing was deleted: both places hold every page.
      _readBoth(subtree, from, to);
      expect(_dups, hasLength(subtree.length));
      await verify('after the crash in a copy (seed $seed)', fresh: true);
      await _removeDups();
      return;
    }
    expect(kept, isNotNull, reason: 'the move should have copied and kept the originals: $error');
    nb.syncHook = null;
    _readBoth(subtree, from, to);
    expect(_dups, hasLength(subtree.length), reason: 'every original is kept');
    expect(model[id]!.loc, to, reason: 'the copy is the page');
    switch (variant) {
      case 'copyKeepsOriginal':
        await verify('after a copy that keeps the originals (seed $seed)', fresh: true);
        await nb.deleteOriginals(kept!);
        _dups.clear();
      case 'deleteOriginalCopyChanged':
        // The root's copy changes (another device); its original is kept.
        final y = _newBox(_text('copy edit'));
        _externalWriteSync(id, _disk(id).insertNode(y));
        model[id]!.boxes[y.id] = _val(y);
        await nb.checkFile(_pathOf(id));
        Object? refused;
        try {
          await nb.deleteOriginals(kept!);
        } on NotebookException catch (e) {
          refused = e;
        }
        expect(refused, isNotNull, reason: 'a changed copy keeps its original');
        _dups.removeWhere((d) => !File(d.path).existsSync());
        expect(_dups.map((d) => d.id), contains(id), reason: 'the original of the changed copy stays');
        await verify('after Delete the original with a changed copy (seed $seed)', fresh: true);
        await _removeDups();
      case 'deleteOriginalCrash':
        // The process dies before the n-th original is deleted.
        final at = subtree.length >= 2 ? 2 : 1;
        var n = 0;
        nb.syncHook = (point, _) async {
          if (point != 'originals-before-delete' || ++n < at) return;
          _gone.add(nb);
          nb.dispose();
          throw StateError('crash while deleting the originals');
        };
        Object? crashed;
        try {
          await nb.deleteOriginals(kept!);
        } on Object catch (e) {
          crashed = e;
        }
        expect(crashed, isNotNull, reason: 'the process died while deleting');
        await _restartAfterCrash();
        _readBoth(subtree, from, to);
        expect(_dups.length, lessThanOrEqualTo(subtree.length - (at - 1)), reason: 'the originals before the crash are gone');
        await verify('after a crash in Delete the original (seed $seed)', fresh: true);
        await _removeDups();
    }
  }

  // ---- delete, with undo ------------------------------------------------------

  Future<void> _opDelete() async {
    var variant = _pick(['undo', 'undo', 'keep', 'syncAtDelete', 'failDelete', 'failDelete']);
    if (variant == 'undo') {
      // Some Undos fail on one page (a generator of its own, so the choices of
      // the steps above stay the ones they were).
      final u = _urng.nextInt(5);
      if (u < 2) variant = 'failUndo:retry';
      if (u == 2) variant = 'failUndo:quit';
    }
    // A fault on the last page of a subtree is the one that needs a put-back.
    final parents = [
      for (final e in model.entries)
        if (e.value.parent != null) e.value.parent!,
    ];
    final id = variant == 'failDelete' && parents.isNotEmpty
        ? parents[rng.nextInt(parents.length)]
        : _pickPage();
    final gone = _subtree(id);
    if (_standaloneLeft(gone, to: null) < 1) return; // the app would make a new page
    // Some failed deletes are followed by a kill in the rollback (a generator of
    // its own, so the choices of the steps above stay the ones they were). Only
    // for a subtree of several pages: a single page never reaches the restore.
    if (variant == 'failDelete' && _rrng.nextInt(2) == 0 && gone.length > 1) variant = 'failRollback:kill';
    final m = model[id]!;
    trace.add('delete ${_short(id)} (${gone.length} pages) in ${m.loc}: $variant');
    _kind = 'delete:$variant';
    final st = storeOf(m.loc);
    NotedPage? sync;
    String? syncId;
    if (variant == 'syncAtDelete') {
      // A newer version of the page lands as it is deleted: it is kept.
      final y = _newBox(_text('sync'));
      await nb.flush();
      final base = _disk(id);
      sync = base.insertNode(y);
      syncId = y.id;
      st.beforeDeleteOnce = () => _externalWriteSync(id, sync!);
    } else if (variant == 'failDelete') {
      // The last page of the subtree: the ones before it are already deleted.
      st.failDelete.add(gone.last);
    }
    if (variant == 'failRollback:kill') {
      await _failRollbackKill(id, gone, st);
      return;
    }
    Object? error;
    DeletedPages? deleted;
    try {
      deleted = await nb.delete(id);
    } on Object catch (e) {
      error = e;
    }
    st.failDelete.clear();
    if (variant == 'failDelete') {
      expect(error, isNotNull, reason: 'the delete should have failed');
      return; // the page stays
    }
    expect(error, isNull, reason: 'delete failed: $error');
    // What was deleted, and what was kept because a newer version landed.
    final kept = <String>{if (variant == 'syncAtDelete') id};
    if (kept.isNotEmpty) {
      expect(deleted!.keptNote, isNotNull);
      model[id]!.boxes[syncId!] = _val(sync!.node(syncId)! as BoxRecord);
    }
    final removed = gone.where((p) => !kept.contains(p)).toList();
    final snapshot = {for (final p in removed) p: model[p]!};
    for (final p in removed) {
      model.remove(p);
    }
    if (variant == 'undo' || variant == 'syncAtDelete') {
      await nb.undoDelete(deleted!);
      model.addAll(snapshot);
    } else if (variant == 'keep') {
      nb.discardDeleted(deleted!);
    } else if (variant.startsWith('failUndo')) {
      await _failUndo(variant, deleted!, removed.last, st);
      model.addAll(snapshot);
      if (variant == 'failUndo:quit') {
        // The held page is back as an `-undo-` copy beside its place, which a
        // fresh notebook reads as the page; the other pages are as they were.
        await _verifyFresh('after quitting with a page held (seed $seed)');
        // The sequence goes on from a restart with the copy put in the page's
        // place, as its owner would (the model has a file for the page, not
        // for a copy). This hides nothing the checks look for: the fresh-notebook
        // verify above ran before the rename, with the copy as the only file of
        // the page, and the disk check after the restart still requires exactly
        // the model's files, so a stray or missing file would fail it.
        final copies = dirs[model[removed.last]!.loc]!
            .listSync()
            .whereType<File>()
            .where((f) => f.path.contains('-undo-'))
            .toList();
        expect(copies, hasLength(1), reason: 'quitting wrote one copy, of the held page');
        copies.single.renameSync(_pathOf(removed.last));
        final kind = _kind;
        await _opRestart();
        _kind = kind;
      }
    }
    // Pages kept in the model whose parent is gone are roots now.
    for (final p in model.values) {
      if (p.parent != null && !model.containsKey(p.parent)) p.parent = null;
    }
  }

  /// Regression (run 2026-11-09-01, R-1): a delete whose rollback has not
  /// published its restore yet held its pages only in memory, so a kill then
  /// lost them. [failRollback:kill]: the delete of the last page of [gone] fails,
  /// the rollback stalls at its restore (nothing releases it, no `failNew`), the
  /// app is taken away without a quit, and a fresh notebook must have every page
  /// by its id. After that the hook is released and the app restarts.
  Future<void> _failRollbackKill(String id, List<String> gone, _Chaos st) async {
    final gate = Completer<void>();
    final reached = Completer<void>();
    nb.syncHook = (point, _) async {
      if (point != 'new-before-publish') return;
      if (!reached.isCompleted) reached.complete();
      await gate.future;
    };
    st.failDelete.add(gone.last);
    // Not awaited: it stays in the rollback.
    final outcome = nb.delete(id).then<Object?>((_) => null, onError: (Object e) => e);
    await reached.future.timeout(const Duration(seconds: 20));
    st.failDelete.clear();
    await _verifyFresh('after killing the app in a delete rollback (seed $seed)');
    gate.complete();
    final error = await outcome.timeout(const Duration(seconds: 20));
    nb.syncHook = null;
    expect(error, isNotNull, reason: 'the delete should have failed');
    final kind = _kind;
    await _opRestart();
    _kind = kind;
  }

  /// Regression (run 2026-11-06-01, 0141): an Undo whose write of [victim]
  /// fails used to rethrow and forget the delete, so the page was in no file
  /// after a reload. It must hold the page. `failUndo:retry`: a second Undo
  /// writes it. `failUndo:quit`: quitting writes it beside its place as an
  /// `-undo-` copy, which a fresh notebook lists as the page.
  Future<void> _failUndo(String variant, DeletedPages deleted, String victim, _Chaos st) async {
    st.failNew.add(victim);
    Object? error;
    try {
      await nb.undoDelete(deleted);
    } on Object catch (e) {
      error = e;
    }
    st.failNew.clear();
    expect(error, isA<PagesNotRestoredException>(), reason: 'the failed Undo should hold the page: $error');
    expect(nb.isHeldDelete(deleted), isTrue);
    if (variant == 'failUndo:retry') {
      await nb.undoDelete(deleted);
      expect(nb.isPendingDelete(deleted), isFalse, reason: 'the second Undo wrote the held page');
    } else {
      expect(await nb.prepareToExit(), isTrue);
      expect(nb.isPendingDelete(deleted), isFalse);
    }
  }

  // ---- vanish: a folder goes away with an edit pending; recovery replays -----

  Future<void> _opVanish() async {
    final loc = _pick(['x', 'a']);
    final inLoc = model.entries.where((e) => e.value.loc == loc).toList();
    if (inLoc.isEmpty) return;
    final id = inLoc[rng.nextInt(inLoc.length)].key;
    final m = model[id]!;
    final restart = rng.nextBool();
    final away = _pick(['plain', 'plain', 'syncWhileAway', 'deletedWhileAway', 'replayFails']);
    final how = '${restart ? 'restart' : 'live'}/$away';
    trace.add('vanish $loc with an edit pending on ${_short(id)}: $how');
    _kind = 'vanish:$how';
    await nb.open(id);
    final c = nb.current!;
    _addBox(m, c);
    final dir = dirs[loc]!;
    final awayDir = '${dir.path}-away';
    await _busyRetry(() async => dir.renameSync(awayDir));
    await nb.flush();
    expect((await nb.pendingRecovery()).entries.map((e) => e.pageId), [
      id,
    ], reason: 'the edit was not kept for recovery');
    if (!restart) await nb.checkFolders(); // notices the folder is gone
    if (away == 'syncWhileAway') {
      final y = _newBox(_text('sync'));
      final f = File('$awayDir$sep$id.canvas');
      final page = readPage(f.readAsStringSync());
      await _busyRetry(() => PageStore(Directory(awayDir)).save(page.insertNode(y)));
      m.boxes[y.id] = _val(y);
    } else if (away == 'deletedWhileAway') {
      File('$awayDir$sep$id.canvas').deleteSync();
    }
    await _busyRetry(() async => Directory(awayDir).renameSync(dir.path));
    final st = storeOf(loc);
    if (away == 'replayFails') {
      // The replay's publish fails: the entry must stay.
      st.publishFailures = 500;
    }
    if (restart) {
      _drop();
      nb = _make();
      _spare.add(nb);
      await nb.load();
    } else {
      await nb.checkFolders();
    }
    if (away == 'replayFails') {
      st.publishFailures = 0;
      expect((await nb.pendingRecovery()).entries.map((e) => e.pageId), [
        id,
      ], reason: 'the entry was dropped although the page did not land');
      // The next start replays it.
      _drop();
      nb = _make();
      _spare.add(nb);
      await nb.load();
    }
    expect((await nb.pendingRecovery()).entries, isEmpty, reason: 'the entry was not replayed');
  }

