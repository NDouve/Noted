  Future<void> _binderStep({String? force}) async {
    const order = [
      'found/live',
      'found/restart',
      'removeRestart',
      'movedElsewhere',
      'duplicate/twoRoots',
      'openCopy',
      'upgrade',
      'lockedList',
      'write/unseenReplace',
      'write/refuseOnce',
      'write/coverRefusedThenLands',
      'write/goneAtPublish',
      'write/tightenedBehindOtherDelta',
      'write/crashAside',
      'write/missingThenBack',
      'write/foreignAfterMissing',
      'write/heldThenUse',
    ];
    final kind = force ?? order[(seed + _binderStepCount++) % order.length];
    trace.add('binder step: $kind');
    switch (kind) {
      case 'found/live':
        final id = _newBinderId();
        final dir = await _deviceBinder(id, inDefaultFolder: _brng.nextBool());
        await nb.discoverBinders();
        _foundListed[_norm(dir)] = id;
      case 'found/restart':
        final id = _newBinderId();
        final dir = await _deviceBinder(id, inDefaultFolder: _brng.nextBool());
        await _opRestart();
        await nb.discoveryIdle;
        _foundListed[_norm(dir)] = id;
      case 'removeRestart':
        final target = await _someFound();
        await nb.removeBinder(_listedPath(target));
        _removedIds.add(_foundListed.remove(target)!);
        await _opRestart();
      case 'movedElsewhere':
        final target = await _someFound();
        final id = _foundListed[target]!;
        final from = Directory(_devReal[target]!);
        final to = Directory('${from.path}-moved');
        await _busyRetry(() async => from.rename(to.path));
        _devFolders
          ..remove(target)
          ..[_norm(to.path)] = id;
        _devReal
          ..remove(target)
          ..[_norm(to.path)] = to.path;
        await nb.checkFolders();
        await nb.discoverBinders();
        // Listed at the old folder (now away); the new folder is only a hint.
        expect(nb.binderMovedTo(_listedPath(target)).map(_norm), [_norm(to.path)], reason: 'seed $seed: the hint');
        await verify('binder moved away');
        await _busyRetry(() async => to.rename(from.path));
        _devFolders
          ..remove(_norm(to.path))
          ..[target] = id;
        _devReal
          ..remove(_norm(to.path))
          ..[target] = from.path;
        await nb.checkFolders();
        await nb.discoverBinders();
      case 'duplicate/twoRoots':
        final id = _newBinderId();
        await _deviceBinder(id, inDefaultFolder: false, name: 'Twin${_binderCounter}a');
        await _deviceBinder(id, inDefaultFolder: true, name: 'Twin${_binderCounter}b');
        await nb.discoverBinders();
        expect(nb.discoveryNotes.where((n) => n.reason.contains(id) || n.reason.contains('Twin')), isNotEmpty);
      case 'openCopy':
        final copy = Directory('${root.path}${sep}Copy${++_binderCounter}')..createSync();
        File('${dirs['a']!.path}$sep$binderFileName').copySync('${copy.path}$sep$binderFileName');
        final inA = model.entries.where((e) => e.value.loc == 'a').map((e) => e.key).firstOrNull;
        if (inA != null) File(_pathOf(inA)).copySync('${copy.path}$sep$inA.canvas');
        _devFolders[_norm(copy.path)] = _idA;
        await nb.discoverBinders();
        for (final f in [if (inA != null) '$inA.canvas', binderFileName]) {
          Object? refused;
          try {
            await openExistingFile(nb, '${copy.path}$sep$f');
          } on NotebookException catch (e) {
            refused = e;
          }
          expect(refused, isNotNull, reason: 'seed $seed: a copy of a listed binder is refused ($f)');
        }
      case 'write/unseenReplace':
        if (!_canWrite) return;
        final v = _pickAi();
        final b = Binder.parse(_aFile.readAsStringSync()).withOwner('Them $seed');
        await _busyRetry(() async => _aFile.writeAsStringSync(b.write().replaceFirst('{', '{"x-future":{"k":1},')));
        _aForeign = true;
        await nb.setBinderAiAccess(pathA, v);
        _aAi = v;
      case 'write/refuseOnce':
        if (!_canWrite) return;
        final want = _aImg == false ? null : false;
        _seams.failMoves = 5;
        await nb.setBinderBoxType(pathA, 'image', want);
        await nb.checkBinderFile(_aFile.path);
        expect(_sectionA.binder?.boxTypeChoice('image'), _aImg, reason: 'seed $seed: the saved value is shown again');
        _seams.failMoves = 0;
        await nb.setBinderBoxType(pathA, 'image', want);
        _aImg = want;
      case 'write/coverRefusedThenLands':
        if (!_canWrite) return;
        final t = 'Title $seed.${++_titleCounter}';
        _seams.failMoves = 5;
        expect(await nb.updateBinder(pathA, title: t), isFalse, reason: 'seed $seed: refused');
        expect(nb.coverNotSaved(pathA), isTrue);
        _seams.failMoves = 0;
        await realIoUntil(() => nb.coverPendingCountForTest(pathA) == 0, 'the cover change to land');
        _aTitle = t;
      case 'write/goneAtPublish':
        if (!_canWrite) return;
        var v = _pickAi();
        // A value the file already holds writes nothing, so nothing is left to put back.
        final held = Binder.parse(_aFile.readAsStringSync()).aiAccess ?? AiAccess.guarded;
        if (v == held) v = AiAccess.values[(v.index + 1) % AiAccess.values.length];
        _seams.beforeMoveAside = () {
          _seams.beforeMoveAside = null;
          _busySync(() => _aFile.deleteSync());
        };
        await nb.setBinderAiAccess(pathA, v);
        await nb.checkBinderFile(_aFile.path);
        expect(_sectionA.status, BinderStatus.unavailable, reason: 'seed $seed: the file is gone');
        final rows = nb.binderCopyRows(_sectionA);
        expect(rows, hasLength(1), reason: 'seed $seed: the temp is listed (${rows.map((r) => "${r.name} ${r.label}").join(", ")})');
        await nb.putBackBinderCopy(pathA, rows.single.path);
        await nb.checkBinderFile(_aFile.path);
        // The copy held the change.
        _aAi = Binder.parse(_aFile.readAsStringSync()).aiAccess;
        expect(_aAi, v == AiAccess.guarded ? anyOf(v, isNull) : v);
      case 'write/tightenedBehindOtherDelta':
        if (!_canWrite || !model.values.any((m) => m.loc == 'a')) return; // (the check below needs a page in A)
        if ((_aAi ?? AiAccess.guarded) == AiAccess.guarded) {
          await nb.setBinderAiAccess(pathA, AiAccess.open);
          _aAi = AiAccess.open;
        }
        final tighter = _aAi == AiAccess.open ? AiAccess.privileged : AiAccess.guarded;
        final t = 'Title $seed.${++_titleCounter}';
        final gate = _seams.holdNext();
        final first = nb.updateBinder(pathA, title: t);
        final second = nb.setBinderAiAccess(pathA, tighter);
        final inA = model.entries.firstWhere((e) => e.value.loc == 'a').key;
        expect(
          nb.aiAccessFor(inA).value.strictness,
          greaterThanOrEqualTo(tighter.strictness),
          reason: 'seed $seed: the tightening counts at once',
        );
        gate.complete();
        await Future.wait([first, second]);
        _aTitle = t;
        _aAi = tighter;
      case 'write/crashAside':
        if (!_canWrite) return;
        await nb.flush();
        await nb.discoveryIdle;
        final bytes = _aFile.readAsBytesSync();
        File('${dirs['a']!.path}$sep$binderFileName.4242-${seed.toRadixString(16)}-ab12.cas-old')
            .writeAsBytesSync(bytes);
        await _busyRetry(() async => _aFile.deleteSync());
        await _opRestart();
        await nb.discoveryIdle;
        expect(_aFile.readAsBytesSync(), bytes, reason: 'seed $seed: the aside was put back');
        expect(_sectionA.available, isTrue, reason: 'seed $seed: available, its pages listed');
      case 'write/missingThenBack':
        if (!_canWrite) return;
        final pageInA = model.entries.where((e) => e.value.loc == 'a').firstOrNull?.key;
        if (pageInA != null) await nb.open(pageInA);
        await nb.flush();
        final bytes = _aFile.readAsBytesSync();
        await _busyRetry(() async => _aFile.deleteSync());
        await nb.checkBinderFile(_aFile.path);
        expect(_sectionA.status, BinderStatus.unavailable, reason: 'seed $seed: unavailable at once');
        final t = 'Title $seed.${++_titleCounter}';
        await nb.updateBinder(pathA, title: t);
        expect(nb.coverPendingCountForTest(pathA), 1, reason: 'seed $seed: the change waits');
        await _busyRetry(() async => _aFile.writeAsBytesSync(bytes));
        await nb.checkBinderFile(_aFile.path);
        await realIoUntil(() => nb.coverPendingCountForTest(pathA) == 0, 'the waiting change to land');
        if (pageInA != null) expect(nb.currentId, pageInA, reason: 'seed $seed: the page that was open is open again');
        _aTitle = t;
      case 'write/foreignAfterMissing':
        if (!_canWrite) return;
        await nb.flush();
        await _busyRetry(() async => _aFile.deleteSync());
        await nb.checkBinderFile(_aFile.path);
        final other = Binder.create(id: _newBinderId(), title: 'Foreign $seed', color: binderPalette[2]);
        await _busyRetry(() async => _aFile.writeAsStringSync(other.write()));
        await nb.checkBinderFile(_aFile.path);
        expect(_sectionA.other?.id, other.id, reason: 'seed $seed: another binder is listed read-only');
        expect(_sectionA.binder, isNull);
        _aOther = true;
        // The live notebook and a fresh one agree, and the file is untouched.
        await verify('another binder in the folder', fresh: true);
        expect(_aFile.readAsStringSync(), other.write());
        await nb.useThisBinder(pathA);
        _aOther = false;
        _idA = other.id;
        _aTitle = other.title;
        _aAi = null;
        _aImg = null;
        _aForeign = false;
      case 'write/heldThenUse':
        await _heldStep('other');
      case final k when k.startsWith('write/held/'):
        await _heldStep(k.substring('write/held/'.length));
      case 'lockedList':
        await _lockedList(damaged: _brng.nextBool());
      case 'lockedList/locked':
        await _lockedList(damaged: false);
      case 'lockedList/damaged':
        await _lockedList(damaged: true);
      case 'upgrade':
        await nb.flush();
        await nb.discoveryIdle;
        _drop();
        // The file as an older build leaves it: no ids, no removals.
        final text = settings.readAsStringSync();
        final map = jsonDecode(text) as Map<String, Object?>
          ..remove('binderIds')
          ..remove('removedBinders');
        settings.writeAsStringSync(jsonEncode(map));
        final id = _newBinderId();
        await _deviceBinder(id, inDefaultFolder: _brng.nextBool());
        nb = _make();
        _spare.add(nb);
        await nb.load();
        await nb.discoveryIdle;
        // Every binder found that isn't listed on an available path is recorded
        // as removed, not listed.
        final listedIds = {_idA, _idB, ..._foundListed.values};
        _removedIds
          ..clear()
          ..addAll(_devFolders.values.toSet().difference(listedIds));
    }
    await verify('binder step $kind');
    kinds.add(kind.startsWith('lockedList') ? 'binder:lockedList' : 'binder:$kind');
  }

  // Held edits (run 2026-11-16-01, task 3): an edit of the open page in A with
  // its autosave pending, then A's folder stops holding binder A ([leg]):
  //   other, freshThenUse: another binder's file (with a delete queued behind
  //     a job at the folder), then Use this binder (on the live notebook, or on
  //     a fresh launch);
  //   damaged, missing: a damaged binder file, or none, then the original back;
  //   transient: half-written bytes at a save's turn, then the same bytes back
  //     (no hold: the save is retried);
  //   queuedScan: a scan queued at the folder with a page-file aside, across
  //     the swap (no sweep);
  //   attachments: a damaged attachment and a missing one with a kept copy,
  //     displayed while held (nothing renamed or put back);
  //   templateSave, templateSweep, templateDelete: template work queued at the
  //     folder across the swap (nothing written in `<A>/templates`).
  // While held, nothing is written to A, and the folder's files (templates
  // included) and its recovery entries are the same live and after a fresh
  // launch. Afterwards the edit lands and the model holds.
  // What the page files of [d] hold (each box's id, text and bounds, and the
  // title), and what recovery keeps for A.
  Map<String, Object> _landedState(Directory d) => {
    for (final f in d.listSync().whereType<File>())
      if (f.path.endsWith('.canvas'))
        f.path.split(RegExp(r'[\\/]')).last: () {
          final p = readPage(f.readAsStringSync());
          return [
            'title ${p.meta.title}',
            ...[for (final n in p.nodes) if (n is BoxRecord) '${n.id} ${n.snapshotText} ${n.bounds}']..sort(),
          ].join('\n');
        }(),
    'recovery for A': '${nb.heldPagesFor(pathA)}',
  };

  Future<void> _heldStep(String leg) async {
    if (!_canWrite) return;
    final inA = [for (final e in model.entries) if (e.value.loc == 'a') e.key];
    if (inA.isEmpty) return;
    final dirA = dirs['a']!;
    final id = inA.first;
    trace.add('  held: $leg on ${_short(id)}');
    await nb.open(id);
    await nb.flush();
    final original = _aFile.readAsBytesSync();
    final other = Binder.create(id: _newBinderId(), title: 'Held $seed', color: binderPalette[3]);
    final templates = Directory('${dirA.path}${sep}templates');
    final aside = File('${dirA.path}$sep$id.canvas.42-aa-bb$asideSuffix');
    final made = <File>[];
    TemplateItem? item;
    if (leg == 'templateDelete') {
      await nb.savePageAsTemplate(id, name: 'Held $seed', inBinder: true);
      item = (await nb.listTemplates(TemplateKind.page, binderPath: pathA)).items.firstWhere((i) => i.binderPath != null);
    }
    if (leg == 'templateSweep') {
      templates.createSync(recursive: true);
      made.add(File('${templates.path}${sep}x.notedtemplate.4242-a-b$asideSuffix')..writeAsStringSync('left'));
    }
    if (leg == 'queuedScan') {
      aside.writeAsStringSync(File(_pathOf(id)).readAsStringSync());
      made.add(aside);
    }
    final good = utf8.encode('the good file $seed');
    final another = utf8.encode('another file $seed');
    final keptName = attachmentFileName(contentHash(good), 'txt');
    final damagedName = attachmentFileName(contentHash(another), 'txt');
    final assets = Directory(_assetsPath(id));
    final hadAssets = assets.existsSync();
    if (leg == 'attachments') {
      assets.createSync(recursive: true);
      made
        ..add(File('${assets.path}$sep$keptName.kept-1')..writeAsBytesSync(good))
        ..add(File('${assets.path}$sep$damagedName')..writeAsBytesSync([...another.reversed]));
    }
    _localEdit(model[id]!, nb.current!, addOnly: true);

    // Runs [op] queued behind a job the test holds at A, with A's file replaced
    // by another binder's while it waits.
    Future<Object?> queued(Future<Object?> Function() op) async {
      final release = Completer<void>();
      final holding = nb.folderLocks.run(dirA, () => release.future);
      final running = op().then<Object?>((r) => r, onError: (Object e) => e);
      await Future<void>.delayed(const Duration(milliseconds: 30));
      await _busyRetry(() async => _aFile.writeAsStringSync(other.write()));
      release.complete();
      await holding;
      return running;
    }

    switch (leg) {
      case 'other' || 'freshThenUse' || 'attachments':
        final victim = inA.length > 1 ? inA[1] : null;
        final r = await queued(() async => victim == null ? null : await nb.delete(victim));
        if (victim != null) expect(r, isA<NotebookException>(), reason: 'seed $seed: the queued delete is refused');
      case 'queuedScan':
        await queued(() => nb.scanLocationForTest(pathA));
        expect(aside.existsSync(), isTrue, reason: 'seed $seed: the queued scan swept nothing');
      case 'templateSave':
        final r = await queued(() => nb.savePageAsTemplate(id, name: 'Late', inBinder: true));
        expect(r, isA<NotebookException>(), reason: 'seed $seed: the queued template save is refused');
      case 'templateSweep':
        await queued(() => nb.listTemplates(TemplateKind.page, binderPath: pathA));
        expect(made.single.existsSync(), isTrue, reason: 'seed $seed: the leftover is not swept');
      case 'templateDelete':
        final r = await queued(() => nb.deleteTemplate(item!));
        expect(r, isA<NotebookException>(), reason: 'seed $seed: the queued template delete is refused');
        expect(File(item!.path).existsSync(), isTrue);
      case 'damaged':
        await _busyRetry(() async => _aFile.writeAsStringSync('{ not json'));
      case 'missing':
        await _busyRetry(() async => _aFile.deleteSync());
      case 'transient':
        var fired = false;
        nb.syncHook = (point, path) async {
          if (point == 'binder-gate' && !fired) {
            fired = true;
            await _busyRetry(() async => _aFile.writeAsStringSync('{"format":1,"binderId":'));
          }
        };
        await nb.flush();
        nb.syncHook = null;
        await _busyRetry(() async => _aFile.writeAsBytesSync(original));
        expect(fired, isTrue, reason: 'seed $seed: the save reached its turn');
        expect(_sectionA.hold, isNull, reason: 'seed $seed: a half-written file holds nothing');
        expect(nb.heldPagesFor(pathA), 1, reason: 'seed $seed: the edit is kept');
        await realIoUntil(() => nb.heldPagesFor(pathA) == 0, 'the retried save to land');
        return;
    }
    await nb.checkBinderFile(_aFile.path);
    await nb.afterHoldForTest(pathA);
    final hold = switch (leg) {
      'damaged' => BinderHold.damaged,
      'missing' => BinderHold.missing,
      _ => BinderHold.otherBinder,
    };
    expect(_sectionA.hold, hold, reason: 'seed $seed: the folder is held ($leg)');
    expect(nb.heldPagesFor(pathA), 1, reason: 'seed $seed: the edit is kept');
    if (leg != 'missing') expect(nb.isReadOnlyPage(id), isTrue, reason: 'seed $seed: its pages are read-only');

    // The folder's files and the recovery entries kept for it, by path.
    bool forA(File f) {
      try {
        final m = jsonDecode(f.readAsStringSync());
        return m is Map && m['folder'] is String && _norm(m['folder'] as String) == _norm(pathA);
      } on Object {
        return false;
      }
    }

    Map<String, String> bytes() => {
      for (final f in dirA.listSync(recursive: true).whereType<File>()) f.path: base64Encode(f.readAsBytesSync()),
      if (rec.existsSync())
        for (final f in rec.listSync(recursive: true).whereType<File>())
          if (f.path.endsWith('.entry') && forA(f)) f.path: base64Encode(f.readAsBytesSync()),
    };
    final before = bytes();
    if (leg == 'attachments') {
      final store = nb.attachments!;
      expect((await store.verify(keptName, size: good.length)).state, AttachmentState.syncing);
      expect((await store.verify(damagedName, size: another.length)).state, AttachmentState.damaged);
      expect(bytes(), before, reason: 'seed $seed: displaying the held attachments changed nothing');
    }
    final live = bytes();
    final fresh = _make();
    _spare.add(fresh);
    try {
      await fresh.load();
      final s = fresh.binders.firstWhere((b) => _norm(b.path) == _norm(pathA));
      expect(s.available, isFalse, reason: 'seed $seed: a fresh launch lists A read-only or unavailable too');
      if (hold == BinderHold.otherBinder) expect(s.hold, hold, reason: 'seed $seed: and holds it');
      expect(fresh.heldPagesFor(pathA), 1, reason: 'seed $seed: and keeps the edit');
      if (leg == 'attachments') {
        await fresh.open(id);
        await fresh.attachments!.verify(keptName, size: good.length);
        await fresh.attachments!.verify(damagedName, size: another.length);
      }
      expect(bytes(), live, reason: 'seed $seed: the folder, its templates and its recovery are as the live notebook left them');
    } finally {
      if (_gone.add(fresh)) fresh.dispose();
    }

    // What the leg made goes before the folder is this binder's again.
    for (final f in made) {
      if (f.existsSync()) f.deleteSync();
    }
    if (leg == 'attachments' && !hadAssets && assets.existsSync() && assets.listSync().isEmpty) assets.deleteSync();
    if (templates.existsSync()) await _busyRetry(() => templates.delete(recursive: true));

    switch (leg) {
      case 'damaged' || 'missing':
        await _busyRetry(() async => _aFile.writeAsBytesSync(original));
        await nb.checkBinderFile(_aFile.path);
        await nb.afterHoldForTest(pathA);
      case 'freshThenUse':
        // Use this binder live, then the same held state again (put back on
        // disk) with a fresh launch and Use this binder there: the page files
        // and recovery come out the same.
        final held = {...bytes(), settings.path: base64Encode(settings.readAsBytesSync())};
        await nb.useThisBinder(pathA);
        await nb.flush();
        await realIoUntil(() => nb.heldPagesFor(pathA) == 0, 'the kept edit to land (live)');
        final afterLive = _landedState(dirA);
        await nb.flush();
        _drop();
        for (final f in dirA.listSync(recursive: true).whereType<File>()) {
          if (!held.containsKey(f.path)) f.deleteSync();
        }
        if (rec.existsSync()) {
          for (final f in rec.listSync(recursive: true).whereType<File>()) {
            if (f.path.endsWith('.entry') && forA(f) && !held.containsKey(f.path)) f.deleteSync();
          }
        }
        for (final e in held.entries) {
          File(e.key)
            ..parent.createSync(recursive: true)
            ..writeAsBytesSync(base64Decode(e.value));
        }
        nb = _make();
        _spare.add(nb);
        await nb.load();
        expect(_sectionA.hold, BinderHold.otherBinder, reason: 'seed $seed: held again after the put-back');
        await nb.useThisBinder(pathA);
        await nb.flush();
        await realIoUntil(() => nb.heldPagesFor(pathA) == 0, 'the kept edit to land (fresh)');
        expect(_landedState(dirA), afterLive, reason: 'seed $seed: Use this binder live and after a fresh launch agree');
      default:
        await nb.useThisBinder(pathA);
    }
    if (hold == BinderHold.otherBinder) {
      _idA = other.id;
      _aTitle = other.title;
      _aAi = null;
      _aImg = null;
      _aForeign = false;
    }
    await nb.flush();
    await realIoUntil(() => nb.heldPagesFor(pathA) == 0, 'the kept edit to land');
  }

  // A launch that can't read binders.json (locked, or damaged), then a retry that
  // can: binder changes are refused meanwhile, nothing is written, and after the
  // retry a removal is recorded and a restart agrees.
  Future<void> _lockedList({required bool damaged}) async {
    final target = await _someFound();
    final path = _devReal[target]!;
    await nb.flush();
    await nb.discoveryIdle;
    final original = settings.readAsBytesSync();
    _drop();
    if (damaged) settings.writeAsStringSync('{oops');
    final held = settings.readAsBytesSync();
    nb = _make();
    _spare.add(nb);
    var fired = 0;
    nb.binderHook = (point, p) async {
      if (point != 'settings-read') return;
      fired++;
      if (!damaged) throw FileSystemException('locked by another program', p);
    };
    await nb.load();
    expect(fired, 1, reason: 'seed $seed: the read hook fired');
    expect(nb.settingsHoldForTest, damaged ? 'damaged' : 'locked', reason: 'seed $seed');
    expect(nb.binders, isEmpty, reason: 'seed $seed: hidden while held');
    // With every page in a binder or folder that is hidden, load makes a page.
    final made = nb.currentId;
    if (made != null && !model.containsKey(made)) {
      model[made] = _MPage('pages');
      nb.current!.insertBox(_opaqueBox());
      _addBox(model[made]!, nb.current!);
      await nb.flush();
    }
    final fresh = Directory('${root.path}${sep}New${++_binderCounter}')..createSync();
    for (final change in [
      () => nb.addBinder(fresh.path),
      () => nb.createPage(folderPath: fresh.path),
      () => nb.removeBinder(path),
    ]) {
      Object? refused;
      try {
        await change();
      } on NotebookException catch (e) {
        refused = e;
      }
      expect(refused, isNotNull, reason: 'seed $seed: a change while held is refused');
    }
    fresh.deleteSync(recursive: true);
    expect(settings.readAsBytesSync(), held, reason: 'seed $seed: nothing was written while held');
    await nb.retrySettings(); // the retries the refusals started end first
    if (damaged) settings.writeAsBytesSync(original);
    nb.binderHook = null;
    expect(await nb.retrySettings(), isTrue, reason: 'seed $seed: the retry adopts the list');
    await nb.discoveryIdle;
    await nb.removeBinder(_listedPath(target));
    _removedIds.add(_foundListed.remove(target)!);
    await _opRestart();
  }


