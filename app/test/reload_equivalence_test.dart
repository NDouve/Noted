// Reload equivalence (run 2026-11-03-01, task D6): seeded sequences of saves,
// external edits, conflict copies, moves, deletes with undo and recovery
// replays, with faults injected through the store hooks, against a simple
// model of what every page holds. After each step the files on disk must equal
// the model, and after each sequence so must a fresh `Notebook` loaded from the
// same folders (0020, 0051, 0053, 0070, 0124, 0130, 0131).
//
// The model. Per page: its location (the default folder, a second standalone
// folder, or one of two binders), its parent, its title and its boxes as
// box id to text. Every step changes the model by what a user and a sync
// client would have done, then the check below compares it with the world.
//
// What is compared (see `_Run.verify`):
//  1. each folder holds exactly the model's page files (and the binder files):
//     nothing missing, no deleted page back, no conflict copy, set-aside or
//     temporary file left over;
//  2. each page file, read back, has the model's boxes, title and parent, and
//     no box is conflicted;
//  3. the open page in the live notebook shows the same boxes as its file;
//  4. no recovery entry or recovery problem is pending and no file is listed
//     as unreadable (the live notebook finished everything it started);
//  5. a fresh notebook over the same folders lists the same pages in the same
//     places and shows the same boxes for each one (end of the sequence).
//
// Normalisations. Boxes are compared as id to text only, so these are not
// compared: the `noted.device` and `noted.at` stamps, box revisions (`rev`,
// `baseRev`), the `landed` marker a merge puts on a box that came from another
// device, bounds, and the order of the nodes and of sibling pages. Box ids are
// made by the model (seed and a counter), so they are the same on both sides;
// an id the app generated (a box kept under a new id) would show as a box the
// model doesn't know and fail. Page ids are generated by the app and are
// learned from it. Conflicted boxes are never normalised away: the operations
// never edit one box on two sides, so any conflict is a failure.
//
// Mutations. Each row below was made by breaking the named behaviour for one
// run of the first 16 seeds (the suite has 24 now) (edit the source, run this file, restore it). The count
// is how many of those 16 sequences failed, and what it says is the check that
// caught it.
//
//  1. `Notebook._enqueueSave` does not look at the file before a save of the
//     open page (the `_checkFile` call): 6 fail; "boxes of page" and "the
//     files in" after `edit` steps, "the entry was not replayed".
//  2. `replaceIfUnchanged` deletes the set-aside original instead of keeping it
//     as a conflict copy when a sync writer takes the target at the publish:
//     4 fail; "boxes of page" after `conflict:stealPublish` (the original-only
//     box is lost).
//  3. `RecoveryStore.write` keeps nothing: 15 fail; "the edit was not kept for
//     recovery" at every `vanish` step.
//  4. `Notebook._deleteIfUnchanged` deletes whatever file is there: 11 fail;
//     "the move should have been refused" (`move:syncAtSource` loses the newer
//     version).
//  5. `undoDelete` does nothing: 7 fail; "the files in pages|a|b" after
//     `delete:undo`.
//  6. The recovery replay writes the entry without merging the saved file: 3
//     fail; "the entry was not replayed" and the other device's box lost
//     (`vanish:*/syncWhileAway`).
//  7. `_writeIfUnchanged` overwrites instead of compare-and-swap: 13 fail;
//     "boxes of page" after `edit:sync*`, `rename:sync*` and `conflict:*`
//     steps, "the sync writer never got its turn", "the entry was dropped
//     although the page did not land".
//  8. The conflict-copy merge ignores the copy: 14 fail; "the files in" (the
//     copy is left or its boxes missing) after `conflict` steps.
//  9. An external change is not merged into the open page: 11 fail; "boxes of
//     page" after `external` and `edit` steps, "the entry was not replayed".
// 10. A move's rollback (`removeCopies`) removes nothing: 6 fail; "the files
//     in a|b|x" after `move:failDestination` on a subtree (the first page's
//     copy is left at the target). Before the move faults were aimed at the
//     last page of a subtree this mutation was not caught at all.
// 11. A move whose source delete fails leaves its copy at the target: 5 fail;
//     "the files in a|b" after `move:failSourceDelete`.
// 12. A publish that fails does not put the set-aside original back: 4 fail;
//     "the files in" (a `.cas-verified` file where the page was) after
//     `edit:failAlways`.
// 13. `Notebook.delete` does not put back what a failed delete already deleted
//     (the fix of this task): 5 of the 24 sequences (seeds 3, 10, 13, 19, 20) and
//     the regression probes fail; "the files in pages" after
//     `delete:failDelete` on a page with subpages, and the regression probe.
//     The generator aims the fault at the last page of the subtree for this.
// 14. A merge re-serialises the data of the unregistered box (invariant 2): all
//     24 fail; "data of the unregistered box" on disk, first after `vanish`
//     and `copy` steps.
// 15. A page that could not be put back overwrites the recovery entry already
//     waiting for it: the probe "a failed put-back with a recovery entry
//     waiting ..." fails ("the pending edit was replaced"). The same probe
//     checks that attachments which cannot go back are handed to recovery's
//     kept files and come back after a later delete and a restart.
//
// Wait for watchers: none is used. The notebook runs with `watchFiles` off,
// and the steps call `checkFile` and `checkFolders` themselves, the way the
// watcher would, so a step is over when its calls return. Folder renames and
// the final delete retry while Windows reports the file as in use (errno 32
// and 5), as `conflict_copy_test.dart` does.

