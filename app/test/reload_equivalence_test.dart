Map<String, Object?> _doc(String text) => {
  'document': {
    'type': 'page',
    'children': [
      {
        'type': 'paragraph',
        'data': {
          'delta': [
            {'insert': text},
          ],
        },
      },
    ],
  },
};

/// Runs [op], trying again while Windows reports the file as in use (the
/// notebook reads these files at the same moment, and a rename or delete over
/// a file being read is refused). Gives up after a deadline.
Future<T> _busyRetry<T>(Future<T> Function() op) async {
  final end = DateTime.now().add(const Duration(seconds: 20));
  while (true) {
    try {
      return await op();
    } on FileSystemException catch (e) {
      final code = e.osError?.errorCode;
      final busy = Platform.isWindows && (code == 5 || code == 32);
      if (!busy || DateTime.now().isAfter(end)) rethrow;
      await Future<void>.delayed(const Duration(milliseconds: 25));
    }
  }
}

String _norm(String p) => p.replaceAll(r'\', '/').toLowerCase();

/// A page store that can be made to fail or to be raced at exact moments.
class _Chaos extends PageStore {
  _Chaos(super.directory);

  /// Runs once, before the next write (the compare-and-swap replace or a plain
  /// save): a sync client landing a file at that moment.
  void Function()? beforeWrite;

  /// Runs once, between the set-aside of the original and the publish.
  void Function()? beforePublishOnce;

  /// The next [publishFailures] publishes (of a replace or a new file) fail, as
  /// a disk error would. The replace retries a publish a few times, so a
  /// single failure is masked and a long run of them is not.
  int publishFailures = 0;

  /// Runs once, just before the next compare-and-delete.
  void Function()? beforeDeleteOnce;

  /// Pages whose new file can't be written (a destination that went away).
  final Set<String> failNew = {};

  /// Pages whose file can't be deleted (a source that went away).
  final Set<String> failDelete = {};

  int saves = 0;

  void _failPublish() {
    if (publishFailures <= 0) return;
    publishFailures--;
    throw const FileSystemException('disk error');
  }

  @override
  Future<void> save(NotedPage page) {
    saves++;
    _fire();
    return super.save(page);
  }

  void _fire() {
    final f = beforeWrite;
    beforeWrite = null;
    f?.call();
  }

  @override
  Future<ReplaceResult> saveIfUnchanged(
    NotedPage page,
    String? expectedText, {
    void Function()? beforeMoveAside,
    void Function()? afterRead,
    void Function()? beforePublish,
    void Function()? beforeRestore,
  }) {
    saves++;
    _fire();
    final once = beforePublishOnce;
    beforePublishOnce = null;
    return super.saveIfUnchanged(
      page,
      expectedText,
      beforeMoveAside: beforeMoveAside,
      afterRead: afterRead,
      beforePublish: () {
        once?.call();
        _failPublish();
        beforePublish?.call();
      },
      beforeRestore: beforeRestore,
    );
  }

  @override
  Future<bool> saveNewText(NotedPage page, String text, {Future<void> Function()? beforePublish}) {
    if (failNew.contains(page.id)) throw const FileSystemException('destination gone');
    return super.saveNewText(
      page,
      text,
      beforePublish: () async {
        _failPublish();
        await beforePublish?.call();
      },
    );
  }

  @override
  Future<void> delete(String pageId) {
    if (failDelete.contains(pageId)) throw const FileSystemException('source gone');
    return super.delete(pageId);
  }

  @override
  Future<DeleteResult> deleteIfUnchanged(
    String pageId,
    String expectedText, {
    void Function()? beforeMoveAside,
    void Function()? afterRead,
    Future<void> Function()? beforeDelete,
    void Function()? beforeRestore,
  }) {
    final f = beforeDeleteOnce;
    beforeDeleteOnce = null;
    f?.call();
    if (failDelete.contains(pageId)) throw const FileSystemException('source gone');
    return super.deleteIfUnchanged(
      pageId,
      expectedText,
      beforeMoveAside: beforeMoveAside,
      afterRead: afterRead,
      beforeDelete: beforeDelete,
      beforeRestore: beforeRestore,
    );
  }
}

/// What the model knows of one page.
class _MPage {
  _MPage(this.loc, {this.parent});

  String loc; // 'pages', 'x', 'a' or 'b'
  String? parent;
  String title = 'Untitled page';
  String? assetText; // the one file in the page's attachments folder, if any
  final Map<String, _BoxVal> boxes = {};
}

/// Box text, whatever its nesting: every `insert` string of the note document.
String _textOf(BoxRecord b) {
  final out = StringBuffer();
  void walk(Object? o) {
    if (o is Map) {
      o.forEach((k, v) {
        if (k == 'insert' && v is String) {
          out.write(v);
        } else {
          walk(v);
        }
      });
    } else if (o is List) {
      o.forEach(walk);
    }
  }

  walk(b.data?.decode());
  return out.toString();
}

/// What the model keeps of a note box: its text and its bounds.
typedef _BoxVal = ({String text, Bounds bounds});

_BoxVal _val(BoxRecord b) => (text: _textOf(b), bounds: b.bounds);

/// Every page also holds one box of a type no module registers (invariant 2).
/// Its data is odd on purpose (spacing, key order, an escape) and must come
/// back byte for byte from every save, merge, move, undo and replay.
const String _opaqueType = 'x.unregistered';
const String _opaqueId = '00000000000000f1';
const String _opaqueData = r'{"b":1,  "z":"caf\u00e9", "a":[1, 2 ,3],"n":null}';
const Bounds _opaqueBounds = Bounds(900, 900, 100, 50);

BoxRecord _opaqueBox() => BoxRecord.create(
  id: _opaqueId,
  typeId: _opaqueType,
  dataVersion: 3,
  bounds: _opaqueBounds,
  data: const RawJson.trusted(_opaqueData),
  snapshotText: 'snapshot',
  rev: 'opaquerev',
);

/// The note boxes of [page] as id to text and bounds. Fails on anything that
/// is not a note box, on a conflicted box, and unless the page holds exactly
/// one unregistered box with its data and bounds as they were made.
Map<String, _BoxVal> _boxesOf(NotedPage page, String where) {
  final out = <String, _BoxVal>{};
  var opaque = 0;
  for (final n in page.nodes) {
    if (n is! BoxRecord) fail('$where: a node that is not a box: ${n.id}');
    if (n.isConflicted) fail('$where: box ${n.id} is conflicted (${_textOf(n)})');
    if (n.typeId == _opaqueType) {
      opaque++;
      expect(n.id, _opaqueId, reason: '$where: the unregistered box');
      expect(n.data?.text, _opaqueData, reason: '$where: data of the unregistered box');
      expect(n.bounds, _opaqueBounds, reason: '$where: bounds of the unregistered box');
      continue;
    }
    out[n.id] = _val(n);
  }
  expect(opaque, 1, reason: '$where: the unregistered box is missing or repeated');
  return out;
}

