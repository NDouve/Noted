  Future<void> _opRename() async {
    final id = _pickPage();
    final m = model[id]!;
    final variant = _pick(['plain', 'syncAtPublish', 'syncBeforeWrite']);
    trace.add('rename ${_short(id)} in ${m.loc}: $variant');
    _kind = 'rename:$variant';
    // Close it: open another page.
    if (model.length > 1) await nb.open(_pickPage(where: (i, p) => i != id));
    final st = storeOf(m.loc);
    final title = 'Title ${++_titleCounter}';
    if (variant != 'plain') {
      final y = _newBox(_text('sync'));
      final base = _disk(id);
      var fired = false;
      void hook() {
        fired = true;
        _externalWriteSync(id, base.insertNode(y));
      }

      if (variant == 'syncAtPublish') {
        st.beforePublishOnce = hook;
      } else {
        st.beforeWrite = hook;
      }
      await nb.rename(id, title);
      expect(fired, isTrue);
      m.boxes[y.id] = _val(y);
    } else {
      await nb.rename(id, title);
    }
    m.title = title;
  }

  // ---- move -------------------------------------------------------------------

  List<String> _subtree(String id) {
    final out = [id];
    for (final e in model.entries) {
      if (e.value.parent == id && e.value.loc == model[id]!.loc) out.addAll(_subtree(e.key));
    }
    return out;
  }

  Future<bool> _moveTo(String id, String to) {
    final from = model[id]!.loc;
    return switch (to) {
      'a' => nb.moveToLocation(id, binderPath: pathA),
      'b' => nb.moveToLocation(id, binderPath: pathB),
      'x' => nb.moveToFolder(id, dirs['x']!.path),
      _ => from == 'x' ? nb.moveToFolder(id, dirs['pages']!.path) : nb.moveToLocation(id),
    };
  }

  Future<void> _opMove() async {
    final variant = _pick([
      'plain',
      'plain',
      'plain',
      'pendingEdit',
      'failDestination',
      'failSourceDelete',
      'syncAtSource',
    ]);
    // A fault on the last page of a subtree is the one that needs a rollback.
    final parents = [
      for (final e in model.entries)
        if (e.value.parent != null) e.value.parent!,
    ];
    final fails = variant == 'failDestination' || variant == 'failSourceDelete';
    final id = fails && parents.isNotEmpty ? parents[rng.nextInt(parents.length)] : _pickPage();
    final m = model[id]!;
    final to = _pick(_locs.where((l) => l != m.loc).toList());
    trace.add('move ${_short(id)} ${m.loc} -> $to: $variant');
    _kind = 'move:$variant';
    final from = m.loc;
    final subtree = _subtree(id);
    if (_standaloneLeft(subtree, to: to) < 1) {
      _kind = null;
      return; // a notebook always keeps a standalone page
    }
    var mustFail = false;
    void Function()? syncRestore;
    switch (variant) {
      case 'pendingEdit':
        // An edit not saved yet goes with the page.
        await nb.open(id);
        _localEdit(m, nb.current!);
      case 'failDestination':
        storeOf(to).failNew.add(subtree.last);
        mustFail = true;
      case 'failSourceDelete':
        storeOf(from).failDelete.add(subtree.last);
        mustFail = true;
      case 'syncAtSource':
        // A newer version lands on the source after the move read it.
        final y = _newBox(_text('sync'));
        // Written by the sync writer after every source was checked and before
        // the first is deleted: from a seam of the notebook, outside the guarded
        // delete, so breaking the guard does not remove the competing write.
        await nb.flush();
        final base = _disk(id);
        final prev = nb.syncHook;
        var fired = false;
        nb.syncHook = (point, path) async {
          await prev?.call(point, path);
          if (point != 'move-before-source-delete' || fired) return;
          fired = true;
          _externalWriteSync(id, base.insertNode(y));
        };
        syncRestore = () {
          nb.syncHook = prev;
          expect(fired, isTrue, reason: 'the sync writer never got its turn');
        };
        m.boxes[y.id] = _val(y);
        mustFail = true;
    }
    Object? error;
    var moved = false;
    try {
      moved = await _moveTo(id, to);
    } on Object catch (e) {
      error = e;
    }
    storeOf(to).failNew.clear();
    storeOf(from).failDelete.clear();
    syncRestore?.call();
    if (mustFail) {
      expect(error, isNotNull, reason: 'the move should have been refused');
      return; // everything stays where it was
    }
    expect(error, isNull, reason: 'the move failed: $error');
    expect(moved, isTrue);
    for (final p in subtree) {
      model[p]!.loc = to;
    }
    m.parent = null;
  }

  // ---- delete, with undo ------------------------------------------------------

  Future<void> _opDelete() async {
    var variant = _pick(['undo', 'undo', 'keep', 'syncAtDelete', 'failDelete', 'failDelete']);
    if (variant == 'undo') {
      // Some Undos fail on one page (a generator of its own, so the choices of
      // the steps above stay the ones they were).
      final u = _urng.nextInt(5);
      if (u < 2) variant = 'failUndo:retry';
      if (u == 2) variant = 'failUndo:quit';
    }
    // A fault on the last page of a subtree is the one that needs a put-back.
    final parents = [
      for (final e in model.entries)
        if (e.value.parent != null) e.value.parent!,
    ];
    final id = variant == 'failDelete' && parents.isNotEmpty
        ? parents[rng.nextInt(parents.length)]
        : _pickPage();
    final gone = _subtree(id);
    if (_standaloneLeft(gone, to: null) < 1) return; // the app would make a new page
    // Some failed deletes are followed by a kill in the rollback (a generator of
    // its own, so the choices of the steps above stay the ones they were). Only
    // for a subtree of several pages: a single page never reaches the restore.
    if (variant == 'failDelete' && _rrng.nextInt(2) == 0 && gone.length > 1) variant = 'failRollback:kill';
    final m = model[id]!;
    trace.add('delete ${_short(id)} (${gone.length} pages) in ${m.loc}: $variant');
    _kind = 'delete:$variant';
    final st = storeOf(m.loc);
    NotedPage? sync;
    String? syncId;
    if (variant == 'syncAtDelete') {
      // A newer version of the page lands as it is deleted: it is kept.
      final y = _newBox(_text('sync'));
      await nb.flush();
      final base = _disk(id);
      sync = base.insertNode(y);
      syncId = y.id;
      st.beforeDeleteOnce = () => _externalWriteSync(id, sync!);
    } else if (variant == 'failDelete') {
      // The last page of the subtree: the ones before it are already deleted.
      st.failDelete.add(gone.last);
    }
    if (variant == 'failRollback:kill') {
      await _failRollbackKill(id, gone, st);
      return;
    }
    Object? error;
    DeletedPages? deleted;
    try {
      deleted = await nb.delete(id);
    } on Object catch (e) {
      error = e;
    }
    st.failDelete.clear();
    if (variant == 'failDelete') {
      expect(error, isNotNull, reason: 'the delete should have failed');
      return; // the page stays
    }
    expect(error, isNull, reason: 'delete failed: $error');
    // What was deleted, and what was kept because a newer version landed.
    final kept = <String>{if (variant == 'syncAtDelete') id};
    if (kept.isNotEmpty) {
      expect(deleted!.keptNote, isNotNull);
      model[id]!.boxes[syncId!] = _val(sync!.node(syncId)! as BoxRecord);
    }
    final removed = gone.where((p) => !kept.contains(p)).toList();
    final snapshot = {for (final p in removed) p: model[p]!};
    for (final p in removed) {
      model.remove(p);
    }
    if (variant == 'undo' || variant == 'syncAtDelete') {
      await nb.undoDelete(deleted!);
      model.addAll(snapshot);
    } else if (variant == 'keep') {
      nb.discardDeleted(deleted!);
    } else if (variant.startsWith('failUndo')) {
      await _failUndo(variant, deleted!, removed.last, st);
      model.addAll(snapshot);
      if (variant == 'failUndo:quit') {
        // The held page is back as an `-undo-` copy beside its place, which a
        // fresh notebook reads as the page; the other pages are as they were.
        await _verifyFresh('after quitting with a page held (seed $seed)');
        // The sequence goes on from a restart with the copy put in the page's
        // place, as its owner would (the model has a file for the page, not
        // for a copy). This hides nothing the checks look for: the fresh-notebook
        // verify above ran before the rename, with the copy as the only file of
        // the page, and the disk check after the restart still requires exactly
        // the model's files, so a stray or missing file would fail it.
        final copies = dirs[model[removed.last]!.loc]!
            .listSync()
            .whereType<File>()
            .where((f) => f.path.contains('-undo-'))
            .toList();
        expect(copies, hasLength(1), reason: 'quitting wrote one copy, of the held page');
        copies.single.renameSync(_pathOf(removed.last));
        final kind = _kind;
        await _opRestart();
        _kind = kind;
      }
    }
    // Pages kept in the model whose parent is gone are roots now.
    for (final p in model.values) {
      if (p.parent != null && !model.containsKey(p.parent)) p.parent = null;
    }
  }

  /// Regression (run 2026-11-09-01, R-1): a delete whose rollback has not
  /// published its restore yet held its pages only in memory, so a kill then
  /// lost them. [failRollback:kill]: the delete of the last page of [gone] fails,
  /// the rollback stalls at its restore (nothing releases it, no `failNew`), the
  /// app is taken away without a quit, and a fresh notebook must have every page
  /// by its id. After that the hook is released and the app restarts.
  Future<void> _failRollbackKill(String id, List<String> gone, _Chaos st) async {
    final gate = Completer<void>();
    final reached = Completer<void>();
    nb.syncHook = (point, _) async {
      if (point != 'new-before-publish') return;
      if (!reached.isCompleted) reached.complete();
      await gate.future;
    };
    st.failDelete.add(gone.last);
    // Not awaited: it stays in the rollback.
    final outcome = nb.delete(id).then<Object?>((_) => null, onError: (Object e) => e);
    await reached.future.timeout(const Duration(seconds: 20));
    st.failDelete.clear();
    await _verifyFresh('after killing the app in a delete rollback (seed $seed)');
    gate.complete();
    final error = await outcome.timeout(const Duration(seconds: 20));
    nb.syncHook = null;
    expect(error, isNotNull, reason: 'the delete should have failed');
    final kind = _kind;
    await _opRestart();
    _kind = kind;
  }

  /// Regression (run 2026-11-06-01, 0141): an Undo whose write of [victim]
  /// fails used to rethrow and forget the delete, so the page was in no file
  /// after a reload. It must hold the page. `failUndo:retry`: a second Undo
  /// writes it. `failUndo:quit`: quitting writes it beside its place as an
  /// `-undo-` copy, which a fresh notebook lists as the page.
  Future<void> _failUndo(String variant, DeletedPages deleted, String victim, _Chaos st) async {
    st.failNew.add(victim);
    Object? error;
    try {
      await nb.undoDelete(deleted);
    } on Object catch (e) {
      error = e;
    }
    st.failNew.clear();
    expect(error, isA<PagesNotRestoredException>(), reason: 'the failed Undo should hold the page: $error');
    expect(nb.isHeldDelete(deleted), isTrue);
    if (variant == 'failUndo:retry') {
      await nb.undoDelete(deleted);
      expect(nb.isPendingDelete(deleted), isFalse, reason: 'the second Undo wrote the held page');
    } else {
      expect(await nb.prepareToExit(), isTrue);
      expect(nb.isPendingDelete(deleted), isFalse);
    }
  }

  // ---- vanish: a folder goes away with an edit pending; recovery replays -----

  Future<void> _opVanish() async {
    final loc = _pick(['x', 'a']);
    final inLoc = model.entries.where((e) => e.value.loc == loc).toList();
    if (inLoc.isEmpty) return;
    final id = inLoc[rng.nextInt(inLoc.length)].key;
    final m = model[id]!;
    final restart = rng.nextBool();
    final away = _pick(['plain', 'plain', 'syncWhileAway', 'deletedWhileAway', 'replayFails']);
    final how = '${restart ? 'restart' : 'live'}/$away';
    trace.add('vanish $loc with an edit pending on ${_short(id)}: $how');
    _kind = 'vanish:$how';
    await nb.open(id);
    final c = nb.current!;
    _addBox(m, c);
    final dir = dirs[loc]!;
    final awayDir = '${dir.path}-away';
    await _busyRetry(() async => dir.renameSync(awayDir));
    await nb.flush();
    expect((await nb.pendingRecovery()).entries.map((e) => e.pageId), [
      id,
    ], reason: 'the edit was not kept for recovery');
    if (!restart) await nb.checkFolders(); // notices the folder is gone
    if (away == 'syncWhileAway') {
      final y = _newBox(_text('sync'));
      final f = File('$awayDir$sep$id.canvas');
      final page = readPage(f.readAsStringSync());
      await _busyRetry(() => PageStore(Directory(awayDir)).save(page.insertNode(y)));
      m.boxes[y.id] = _val(y);
    } else if (away == 'deletedWhileAway') {
      File('$awayDir$sep$id.canvas').deleteSync();
    }
    await _busyRetry(() async => Directory(awayDir).renameSync(dir.path));
    final st = storeOf(loc);
    if (away == 'replayFails') {
      // The replay's publish fails: the entry must stay.
      st.publishFailures = 500;
    }
    if (restart) {
      _drop();
      nb = _make();
      _spare.add(nb);
      await nb.load();
    } else {
      await nb.checkFolders();
    }
    if (away == 'replayFails') {
      st.publishFailures = 0;
      expect((await nb.pendingRecovery()).entries.map((e) => e.pageId), [
        id,
      ], reason: 'the entry was dropped although the page did not land');
      // The next start replays it.
      _drop();
      nb = _make();
      _spare.add(nb);
      await nb.load();
    }
    expect((await nb.pendingRecovery()).entries, isEmpty, reason: 'the entry was not replayed');
  }

