class _Run {
  _Run(this.seed) : rng = Random(seed);

  final int seed;
  final Random rng;
  final List<String> trace = [];

  /// The kind of the step being made, and the kinds of the steps that finished
  /// (a step that did nothing, for want of a page to act on, has none).
  String? _kind;
  final List<String> kinds = [];
  final Map<String, _MPage> model = {};
  final Map<String, _Chaos> _stores = {};
  late final ModuleRegistry modules = buildModules();
  late Directory root;
  late Directory rec;
  late File settings;
  late final Map<String, Directory> dirs;
  late Notebook nb;
  late String pathA;
  late String pathB;
  final List<Notebook> _spare = [];
  final Set<Notebook> _gone = {};
  void _drop() {
    if (_gone.add(nb)) nb.dispose();
  }

  int _boxCounter = 0;
  int _copyCounter = 0;
  int _titleCounter = 0;
  final sep = Platform.pathSeparator;

  // -- set-up and tear-down ---------------------------------------------------

  Future<void> start() async {
    root = await Directory.systemTemp.createTemp('noted_reload');
    rec = Directory('${root.path}${sep}rec');
    settings = File('${root.path}${sep}app${sep}binders.json');
    dirs = {
      'pages': await Directory('${root.path}${sep}pages').create(),
      'x': await Directory('${root.path}${sep}Elsewhere').create(),
      'a': await Directory('${root.path}${sep}Alpha').create(),
      'b': await Directory('${root.path}${sep}Beta').create(),
    };
    nb = _make();
    await nb.load();
    final first = nb.currentId!;
    model[first] = _MPage('pages');
    pathA = (await nb.addBinder(dirs['a']!.path)).path;
    pathB = (await nb.addBinder(dirs['b']!.path)).path;
    await nb.addStandaloneFolder(dirs['x']!.path);
    // A page in each place, and a subpage of the first.
    for (final loc in ['a', 'b', 'x']) {
      final id = await nb.createPage(
        binderPath: loc == 'a' ? pathA : (loc == 'b' ? pathB : null),
        folderPath: loc == 'x' ? dirs['x']!.path : null,
      );
      model[id] = _MPage(loc);
    }
    final sub = await nb.createPage(parentId: first);
    model[sub] = _MPage('pages', parent: first);
    for (final id in model.keys.toList()) {
      await nb.open(id);
      nb.current!.insertBox(_opaqueBox());
      _addBox(model[id]!, nb.current!);
      if (rng.nextBool()) _addBox(model[id]!, nb.current!);
      await nb.flush();
    }
    await _settle();
    await verify('set-up');
  }

  Future<void> stop() async {
    for (final n in {nb, ..._spare}) {
      if (_gone.add(n)) n.dispose();
    }
    if (root.existsSync()) await _busyRetry(() => root.delete(recursive: true));
  }

  Notebook _make() => Notebook(
    storeOf('pages'),
    modules,
    saveDelay: const Duration(hours: 1),
    bindersFile: settings,
    recoveryDirectory: rec,
    folderCheckInterval: Duration.zero,
    storeFactory: (d) => _stores.putIfAbsent(_norm(d.path), () => _Chaos(d)),
  );

  _Chaos storeOf(String loc) {
    final d = dirs[loc]!;
    return _stores.putIfAbsent(_norm(d.path), () => _Chaos(d));
  }

  // -- the model's boxes ------------------------------------------------------

  BoxRecord _newBox(String text) {
    final codec = modules.codecs.codecFor('noted.note')!;
    final id = ((seed * 100000 + ++_boxCounter) + 0x1000000000000000).toRadixString(16);
    final at = Bounds(10.0 + 20 * (_boxCounter % 20), 10.0 + 40 * (_boxCounter % 13), 200, 40);
    return commitBox(createBox(codec, at).withId(id), codec, codec.decode(_doc(text), 1));
  }

  String _text(String what) => '$what s$seed.$_boxCounter';

  void _addBox(_MPage m, CanvasController c) {
    final b = _newBox(_text('local'));
    c.insertBox(b);
    m.boxes[b.id] = _val(b);
  }

  /// A local edit on the open page [c]: adds, retexts or deletes a box.
  void _localEdit(_MPage m, CanvasController c, {bool addOnly = false}) {
    final k = addOnly || m.boxes.isEmpty ? 0 : rng.nextInt(10);
    if (k < 6) {
      _addBox(m, c);
    } else if (k < 9) {
      final id = m.boxes.keys.elementAt(rng.nextInt(m.boxes.length));
      final codec = modules.codecs.codecFor('noted.note')!;
      final text = _text('edited');
      c.editBox(id, codec.decode(_doc(text), 1));
      m.boxes[id] = (text: text, bounds: m.boxes[id]!.bounds);
    } else {
      final id = m.boxes.keys.elementAt(rng.nextInt(m.boxes.length));
      c.delete(id);
      m.boxes.remove(id);
    }
  }

  // -- reading the world ------------------------------------------------------

  String _pathOf(String id, [String? loc]) => '${dirs[loc ?? model[id]!.loc]!.path}$sep$id.canvas';

  NotedPage _disk(String id, [String? loc]) => readPage(File(_pathOf(id, loc)).readAsStringSync());

  /// A sync client writing [page] over the page's file, atomically.
  Future<void> _externalWrite(String id, NotedPage page) =>
      _busyRetry(() => PageStore(dirs[model[id]!.loc]!).save(page));

  /// The same, from inside a hook (synchronous; the file is absent or replaced
  /// at that moment, so nothing else could be reading it).
  void _externalWriteSync(String id, NotedPage page) =>
      File(_pathOf(id)).writeAsStringSync(writePage(page));

  String _pick(List<String> items) => items[rng.nextInt(items.length)];

  String _pickPage({bool Function(String id, _MPage m)? where}) {
    final ids = [
      for (final e in model.entries)
        if (where == null || where(e.key, e.value)) e.key,
    ];
    return ids[rng.nextInt(ids.length)];
  }

  // -- the steps --------------------------------------------------------------

  Future<void> step(int n) async {
    try {
      await _step(n);
    } on TestFailure catch (e) {
      if ((e.message ?? '').contains('trace of seed')) rethrow;
      throw TestFailure('${e.message}\n--- trace of seed $seed ---\n${trace.join('\n')}');
    }
  }

  Future<void> _step(int n) async {
    _kind = null;
    final r = rng.nextInt(100);
    final String name;
    if (r < 22) {
      name = 'edit';
      await _opEdit();
    } else if (r < 36) {
      name = 'external';
      await _opExternal();
    } else if (r < 48) {
      name = 'copy';
      await _opCopy();
    } else if (r < 60) {
      name = 'move';
      await _opMove();
    } else if (r < 72) {
      name = 'delete';
      await _opDelete();
    } else if (r < 80) {
      name = 'rename';
      await _opRename();
    } else if (r < 94) {
      name = 'vanish';
      await _opVanish();
    } else {
      name = 'restart';
      await _opRestart();
    }
    trace.add('  ($name done)');
    await _settle();
    await verify('step $n ($name)');
    if (_kind != null) kinds.add(_kind!);
  }

  /// The watcher's job: look at every conflict copy (and set-aside file) left
  /// in the folders until none is left, or give up after a few rounds.
  Future<void> _settle() async {
    for (var round = 0; round < 6; round++) {
      final copies = <String>[];
      for (final loc in _locs) {
        final d = dirs[loc]!;
        if (!d.existsSync()) continue;
        for (final f in d.listSync()) {
          if (f is! File) continue;
          final name = f.path.split(RegExp(r'[\\/]')).last;
          if (name.endsWith('.canvas') && !_isPageFile(name)) copies.add(f.path);
        }
      }
      if (copies.isEmpty) break;
      for (final c in copies) {
        await nb.checkFile(c);
      }
    }
  }

  /// How many standalone pages (default folder, second folder) the model has
  /// once [moving] go to [to] (null: they are gone).
  int _standaloneLeft(List<String> moving, {required String? to}) {
    final standalone = (to == null || to == 'pages' || to == 'x');
    var n = 0;
    for (final e in model.entries) {
      final isStandalone = e.value.loc == 'pages' || e.value.loc == 'x';
      if (moving.contains(e.key)) {
        if (standalone && to != null) n++;
      } else if (isStandalone) {
        n++;
      }
    }
    return n;
  }

  bool _isPageFile(String name) =>
      model.keys.any((id) => name == '$id.canvas') || name == binderFileName;

  // ---- edit: a save of the open page, sometimes raced or failed ---------------

  Future<void> _opEdit() async {
    final id = _pickPage();
    final m = model[id]!;
    final variant = _pick([
      'plain',
      'plain',
      'plain',
      'syncAtPublish',
      'syncBeforeWrite',
      'externalBeforeFlush',
      'failOnce',
      'failAlways',
    ]);
    trace.add('edit ${_short(id)} in ${m.loc}: $variant');
    _kind = 'edit:$variant';
    await nb.open(id);
    final c = nb.current!;
    final st = storeOf(m.loc);
    final racing = variant == 'syncAtPublish' || variant == 'syncBeforeWrite';
    _localEdit(m, c, addOnly: racing || variant == 'externalBeforeFlush');
    switch (variant) {
      case 'plain':
        await nb.flush();
      case 'syncAtPublish':
      case 'syncBeforeWrite':
        // The sync client's version, made from the file as it is now, with a
        // box of its own.
        final y = _newBox(_text('sync'));
        final base = _disk(id);
        var fired = false;
        void hook() {
          fired = true;
          _externalWriteSync(id, base.insertNode(y));
        }

        if (variant == 'syncAtPublish') {
          st.beforePublishOnce = hook;
        } else {
          st.beforeWrite = hook;
        }
        await nb.flush();
        expect(fired, isTrue, reason: 'the sync writer never got its turn');
        m.boxes[y.id] = _val(y);
      case 'externalBeforeFlush':
        // The file changes and no watcher event has run yet.
        final y = _newBox(_text('sync'));
        await _externalWrite(id, _disk(id).insertNode(y));
        await nb.flush();
        m.boxes[y.id] = _val(y);
      case 'failOnce':
        // One failed publish: the replace tries again.
        st.publishFailures = 1;
        await nb.flush();
        expect(st.publishFailures, 0);
      case 'failAlways':
        // The publish keeps failing: the file is put back as it was and the
        // edit stays on the screen. The user types on and the next save lands
        // everything.
        st.publishFailures = 50;
        await nb.flush();
        st.publishFailures = 0;
        _addBox(m, c);
        await nb.flush();
    }
  }

  String _short(String id) => id.substring(0, 4);

  // ---- external: another writer replaces a page file --------------------------

  Future<void> _opExternal() async {
    final id = _pickPage();
    final m = model[id]!;
    trace.add('external edit of ${_short(id)} in ${m.loc}');
    _kind = 'external';
    final page = _disk(id);
    NotedPage next;
    if (m.boxes.isNotEmpty && rng.nextInt(3) == 0) {
      final target = m.boxes.keys.elementAt(rng.nextInt(m.boxes.length));
      final codec = modules.codecs.codecFor('noted.note')!;
      final text = _text('theirs');
      final old = page.node(target)! as BoxRecord;
      next = page.replaceNode(commitBox(old, codec, codec.decode(_doc(text), 1)));
      m.boxes[target] = (text: text, bounds: m.boxes[target]!.bounds);
    } else {
      final y = _newBox(_text('sync'));
      next = page.insertNode(y);
      m.boxes[y.id] = _val(y);
    }
    await _externalWrite(id, next);
    await nb.checkFile(_pathOf(id)); // the watcher's event
  }

  // ---- copy: a sync client's conflict copy appears ----------------------------

  Future<void> _opCopy() async {
    final id = _pickPage();
    final m = model[id]!;
    final variant = _pick([
      'plain',
      'plain',
      'replacedMidMerge',
      'originalChanged',
      'stealPublish',
      'scan',
    ]);
    trace.add('conflict copy of ${_short(id)} in ${m.loc}: $variant');
    _kind = 'conflict:$variant';
    // The merge hooks belong to the closed-page merge: close the page.
    if (variant == 'replacedMidMerge' || variant == 'originalChanged') {
      await nb.open(_pickPage(where: (i, p) => i != id));
    }
    final disk = _disk(id);
    final z = _newBox(_text('copy'));
    final path = '${dirs[m.loc]!.path}$sep$id-DESKTOP-${++_copyCounter}.canvas';
    if (variant == 'stealPublish') {
      if (m.boxes.isEmpty) {
        _kind = null;
        return;
      }
      // R-3 as it happens in a run: the copy and the other device's newer file
      // both lack a box the original has, and the other device's file lands at
      // the publish. The original's own box must survive.
      await nb.open(_pickPage(where: (i, p) => i != id));
      final a = m.boxes.keys.elementAt(rng.nextInt(m.boxes.length));
      final without = disk.removeNode(a);
      final w = _newBox(_text('newer'));
      File(path).writeAsStringSync(writePage(without.insertNode(z)));
      storeOf(m.loc).beforePublishOnce = () => _externalWriteSync(id, without.insertNode(w));
      await nb.checkFile(path);
      await _settle();
      m.boxes[z.id] = _val(z);
      m.boxes[w.id] = _val(w);
      return;
    }
    File(path).writeAsStringSync(writePage(disk.insertNode(z)));
    m.boxes[z.id] = _val(z);
    switch (variant) {
      case 'plain':
        await nb.checkFile(path);
      case 'scan':
        await nb.checkFolders();
      case 'replacedMidMerge':
        // The provider replaces the copy with a newer one while it is merged.
        final later = _newBox(_text('later'));
        var fired = false;
        nb.syncHook = (point, p) async {
          if (point != 'copy-merged' || fired) return;
          fired = true;
          File(path).writeAsStringSync(writePage(disk.insertNode(z).insertNode(later)));
        };
        await nb.checkFile(path);
        nb.syncHook = null;
        expect(fired, isTrue);
        m.boxes[later.id] = _val(later);
      case 'originalChanged':
        // The other device's edit lands on the original after it was read.
        final newer = _newBox(_text('newer'));
        var fired = false;
        nb.syncHook = (point, p) async {
          if (point != 'original-read' || fired) return;
          fired = true;
          await _busyRetry(() => PageStore(dirs[m.loc]!).save(disk.insertNode(newer)));
        };
        await nb.checkFile(path);
        nb.syncHook = null;
        expect(fired, isTrue);
        m.boxes[newer.id] = _val(newer);
    }
  }

  // ---- rename: a closed page is saved, sometimes raced ------------------------

  Future<void> _opRename() async {
    final id = _pickPage();
    final m = model[id]!;
    final variant = _pick(['plain', 'syncAtPublish', 'syncBeforeWrite']);
    trace.add('rename ${_short(id)} in ${m.loc}: $variant');
    _kind = 'rename:$variant';
    // Close it: open another page.
    if (model.length > 1) await nb.open(_pickPage(where: (i, p) => i != id));
    final st = storeOf(m.loc);
    final title = 'Title ${++_titleCounter}';
    if (variant != 'plain') {
      final y = _newBox(_text('sync'));
      final base = _disk(id);
      var fired = false;
      void hook() {
        fired = true;
        _externalWriteSync(id, base.insertNode(y));
      }

      if (variant == 'syncAtPublish') {
        st.beforePublishOnce = hook;
      } else {
        st.beforeWrite = hook;
      }
      await nb.rename(id, title);
      expect(fired, isTrue);
      m.boxes[y.id] = _val(y);
    } else {
      await nb.rename(id, title);
    }
    m.title = title;
  }

  // ---- move -------------------------------------------------------------------

  List<String> _subtree(String id) {
    final out = [id];
    for (final e in model.entries) {
      if (e.value.parent == id && e.value.loc == model[id]!.loc) out.addAll(_subtree(e.key));
    }
    return out;
  }

  Future<bool> _moveTo(String id, String to) {
    final from = model[id]!.loc;
    return switch (to) {
      'a' => nb.moveToLocation(id, binderPath: pathA),
      'b' => nb.moveToLocation(id, binderPath: pathB),
      'x' => nb.moveToFolder(id, dirs['x']!.path),
      _ => from == 'x' ? nb.moveToFolder(id, dirs['pages']!.path) : nb.moveToLocation(id),
    };
  }

  Future<void> _opMove() async {
    final variant = _pick([
      'plain',
      'plain',
      'plain',
      'pendingEdit',
      'failDestination',
      'failSourceDelete',
      'syncAtSource',
    ]);
    // A fault on the last page of a subtree is the one that needs a rollback.
    final parents = [
      for (final e in model.entries)
        if (e.value.parent != null) e.value.parent!,
    ];
    final fails = variant == 'failDestination' || variant == 'failSourceDelete';
    final id = fails && parents.isNotEmpty ? parents[rng.nextInt(parents.length)] : _pickPage();
    final m = model[id]!;
    final to = _pick(_locs.where((l) => l != m.loc).toList());
    trace.add('move ${_short(id)} ${m.loc} -> $to: $variant');
    _kind = 'move:$variant';
    final from = m.loc;
    final subtree = _subtree(id);
    if (_standaloneLeft(subtree, to: to) < 1) {
      _kind = null;
      return; // a notebook always keeps a standalone page
    }
    var mustFail = false;
    switch (variant) {
      case 'pendingEdit':
        // An edit not saved yet goes with the page.
        await nb.open(id);
        _localEdit(m, nb.current!);
      case 'failDestination':
        storeOf(to).failNew.add(subtree.last);
        mustFail = true;
      case 'failSourceDelete':
        storeOf(from).failDelete.add(subtree.last);
        mustFail = true;
      case 'syncAtSource':
        // A newer version lands on the source after the move read it.
        final y = _newBox(_text('sync'));
        // Written before the move reads the source: see below. Armed now, it
        // fires at the first compare-and-delete of the source.
        await nb.flush();
        final base = _disk(id);
        storeOf(from).beforeDeleteOnce = () => _externalWriteSync(id, base.insertNode(y));
        m.boxes[y.id] = _val(y);
        mustFail = true;
    }
    Object? error;
    var moved = false;
    try {
      moved = await _moveTo(id, to);
    } on Object catch (e) {
      error = e;
    }
    storeOf(to).failNew.clear();
    storeOf(from).failDelete.clear();
    if (mustFail) {
      expect(error, isNotNull, reason: 'the move should have been refused');
      return; // everything stays where it was
    }
    expect(error, isNull, reason: 'the move failed: $error');
    expect(moved, isTrue);
    for (final p in subtree) {
      model[p]!.loc = to;
    }
    m.parent = null;
  }

  // ---- delete, with undo ------------------------------------------------------

  Future<void> _opDelete() async {
    final variant = _pick(['undo', 'undo', 'keep', 'syncAtDelete', 'failDelete', 'failDelete']);
    // A fault on the last page of a subtree is the one that needs a put-back.
    final parents = [
      for (final e in model.entries)
        if (e.value.parent != null) e.value.parent!,
    ];
    final id = variant == 'failDelete' && parents.isNotEmpty
        ? parents[rng.nextInt(parents.length)]
        : _pickPage();
    final gone = _subtree(id);
    if (_standaloneLeft(gone, to: null) < 1) return; // the app would make a new page
    final m = model[id]!;
    trace.add('delete ${_short(id)} (${gone.length} pages) in ${m.loc}: $variant');
    _kind = 'delete:$variant';
    final st = storeOf(m.loc);
    NotedPage? sync;
    String? syncId;
    if (variant == 'syncAtDelete') {
      // A newer version of the page lands as it is deleted: it is kept.
      final y = _newBox(_text('sync'));
      await nb.flush();
      final base = _disk(id);
      sync = base.insertNode(y);
      syncId = y.id;
      st.beforeDeleteOnce = () => _externalWriteSync(id, sync!);
    } else if (variant == 'failDelete') {
      // The last page of the subtree: the ones before it are already deleted.
      st.failDelete.add(gone.last);
    }
    Object? error;
    DeletedPages? deleted;
    try {
      deleted = await nb.delete(id);
    } on Object catch (e) {
      error = e;
    }
    st.failDelete.clear();
    if (variant == 'failDelete') {
      expect(error, isNotNull, reason: 'the delete should have failed');
      return; // the page stays
    }
    expect(error, isNull, reason: 'delete failed: $error');
    // What was deleted, and what was kept because a newer version landed.
    final kept = <String>{if (variant == 'syncAtDelete') id};
    if (kept.isNotEmpty) {
      expect(deleted!.keptNote, isNotNull);
      model[id]!.boxes[syncId!] = _val(sync!.node(syncId)! as BoxRecord);
    }
    final removed = gone.where((p) => !kept.contains(p)).toList();
    final snapshot = {for (final p in removed) p: model[p]!};
    for (final p in removed) {
      model.remove(p);
    }
    if (variant == 'undo' || variant == 'syncAtDelete') {
      await nb.undoDelete(deleted!);
      model.addAll(snapshot);
    } else if (variant == 'keep') {
      nb.discardDeleted(deleted!);
    }
    // Pages kept in the model whose parent is gone are roots now.
    for (final p in model.values) {
      if (p.parent != null && !model.containsKey(p.parent)) p.parent = null;
    }
  }

  // ---- vanish: a folder goes away with an edit pending; recovery replays -----

  Future<void> _opVanish() async {
    final loc = _pick(['x', 'a']);
    final inLoc = model.entries.where((e) => e.value.loc == loc).toList();
    if (inLoc.isEmpty) return;
    final id = inLoc[rng.nextInt(inLoc.length)].key;
    final m = model[id]!;
    final restart = rng.nextBool();
    final away = _pick(['plain', 'plain', 'syncWhileAway', 'deletedWhileAway', 'replayFails']);
    final how = '${restart ? 'restart' : 'live'}/$away';
    trace.add('vanish $loc with an edit pending on ${_short(id)}: $how');
    _kind = 'vanish:$how';
    await nb.open(id);
    final c = nb.current!;
    _addBox(m, c);
    final dir = dirs[loc]!;
    final awayDir = '${dir.path}-away';
    await _busyRetry(() async => dir.renameSync(awayDir));
    await nb.flush();
    expect((await nb.pendingRecovery()).entries.map((e) => e.pageId), [
      id,
    ], reason: 'the edit was not kept for recovery');
    if (!restart) await nb.checkFolders(); // notices the folder is gone
    if (away == 'syncWhileAway') {
      final y = _newBox(_text('sync'));
      final f = File('$awayDir$sep$id.canvas');
      final page = readPage(f.readAsStringSync());
      await _busyRetry(() => PageStore(Directory(awayDir)).save(page.insertNode(y)));
      m.boxes[y.id] = _val(y);
    } else if (away == 'deletedWhileAway') {
      File('$awayDir$sep$id.canvas').deleteSync();
    }
    await _busyRetry(() async => Directory(awayDir).renameSync(dir.path));
    final st = storeOf(loc);
    if (away == 'replayFails') {
      // The replay's publish fails: the entry must stay.
      st.publishFailures = 500;
    }
    if (restart) {
      _drop();
      nb = _make();
      _spare.add(nb);
      await nb.load();
    } else {
      await nb.checkFolders();
    }
    if (away == 'replayFails') {
      st.publishFailures = 0;
      expect((await nb.pendingRecovery()).entries.map((e) => e.pageId), [
        id,
      ], reason: 'the entry was dropped although the page did not land');
      // The next start replays it.
      _drop();
      nb = _make();
      _spare.add(nb);
      await nb.load();
    }
    expect((await nb.pendingRecovery()).entries, isEmpty, reason: 'the entry was not replayed');
  }

  // ---- restart ----------------------------------------------------------------

  Future<void> _opRestart() async {
    trace.add('restart');
    _kind = 'restart';
    await nb.flush();
    _drop();
    nb = _make();
    _spare.add(nb);
    await nb.load();
  }

  /// What is left in the app's trash of deleted attachments (`app` beside the
  /// binders file).
  List<FileSystemEntity> trashChildren() {
    final d = Directory('${root.path}${sep}app${sep}deleted-attachments');
    return d.existsSync() ? d.listSync() : const [];
  }

  /// Gives page [id] an attachments folder with a file in it (the probes use
  /// it; the sequences leave attachments alone).
  void _giveAssets(String id) {
    final m = model[id]!;
    m.assetText = 'attachment of $id';
    final d = Directory('${dirs[m.loc]!.path}$sep${assetsFolderName(id)}')..createSync();
    File('${d.path}${sep}a.txt').writeAsStringSync(m.assetText!);
  }

  // -- checks -----------------------------------------------------------------

  Future<void> verify(String when, {bool fresh = false}) async {
    final where = 'seed $seed, $when';
    await nb.flush(); // a merged-in change is saved once more, harmlessly
    String describe() => '\n--- trace of seed $seed ---\n${trace.join('\n')}\n';
    try {
      await _verifyDisk(where);
      await _verifyLive(where);
      if (fresh) await _verifyFresh(where);
    } on TestFailure catch (e) {
      throw TestFailure('${e.message}${describe()}');
    }
  }

  Future<void> _verifyDisk(String where) async {
    for (final loc in _locs) {
      final d = dirs[loc]!;
      final expected = <String>{
        if (loc == 'a' || loc == 'b') binderFileName,
        for (final e in model.entries)
          if (e.value.loc == loc) '${e.key}.canvas',
        for (final e in model.entries)
          if (e.value.loc == loc && e.value.assetText != null) assetsFolderName(e.key),
      };
      final actual = <String>{for (final f in d.listSync()) f.path.split(RegExp(r'[\\/]')).last};
      expect(actual, expected, reason: '$where: the files in $loc');
    }
    for (final e in model.entries) {
      final id = e.key;
      final m = e.value;
      final page = _disk(id);
      if (m.assetText != null) {
        expect(
          File('${dirs[m.loc]!.path}$sep${assetsFolderName(id)}${sep}a.txt').readAsStringSync(),
          m.assetText,
          reason: '$where: the attachment of page ${_short(id)}',
        );
      }
      expect(
        _boxesOf(page, '$where: ${_short(id)} on disk'),
        m.boxes,
        reason: '$where: boxes of page ${_short(id)} in ${m.loc}',
      );
      expect(page.meta.title, m.title, reason: '$where: title of ${_short(id)}');
      expect(page.meta.parentId, m.parent, reason: '$where: parent of ${_short(id)}');
    }
  }

  Future<void> _verifyLive(String where) async {
    final recov = await nb.pendingRecovery();
    expect(recov.entries, isEmpty, reason: '$where: recovery entries are pending');
    expect(recov.problems, isEmpty, reason: '$where: recovery problems');
    expect(nb.recoveryDamaged, isEmpty, reason: '$where: recovery damage');
    expect(nb.unreadable, isEmpty, reason: '$where: unreadable files');
    for (final b in nb.binders) {
      expect(b.unreadable, isEmpty, reason: '$where: unreadable files in ${b.path}');
    }
    expect(nb.unsavedDescription, isNull, reason: '$where: unsaved work');
    final c = nb.current;
    if (c != null && model.containsKey(c.page.id)) {
      final m = model[c.page.id]!;
      expect(_boxesOf(c.page, '$where: the open page'), m.boxes, reason: '$where: the open page');
    }
    for (final e in model.entries) {
      final want = e.value.loc == 'a' ? pathA : (e.value.loc == 'b' ? pathB : null);
      expect(nb.binderOfPage(e.key), want, reason: '$where: binder of ${_short(e.key)}');
    }
  }

  Future<void> _verifyFresh(String where) async {
    final other = Notebook(
      PageStore(dirs['pages']!),
      modules,
      saveDelay: const Duration(hours: 1),
      bindersFile: settings,
      recoveryDirectory: rec,
      folderCheckInterval: Duration.zero,
    );
    _spare.add(other);
    _gone.add(other);
    await other.load();
    try {
      for (final e in model.entries) {
        expect(
          other.treeOfPage(e.key)[e.key],
          isNotNull,
          reason: '$where: a fresh notebook does not list ${_short(e.key)}',
        );
        final want = e.value.loc == 'a' ? pathA : (e.value.loc == 'b' ? pathB : null);
        expect(other.binderOfPage(e.key), want, reason: '$where: fresh binder of ${_short(e.key)}');
        await other.open(e.key);
        expect(
          _boxesOf(other.current!.page, '$where: fresh ${_short(e.key)}'),
          e.value.boxes,
          reason: '$where: a fresh notebook shows page ${_short(e.key)} differently',
        );
        expect(other.current!.page.meta.title, e.value.title);
      }
      final listed = <String>{
        ...other.tree.roots.expand((r) => [r.id, ...other.tree.descendantsOf(r.id)]),
        for (final b in other.binders)
          ...b.tree.roots.expand((r) => [r.id, ...b.tree.descendantsOf(r.id)]),
      };
      expect(listed, model.keys.toSet(), reason: '$where: the pages a fresh notebook lists');
      expect((await other.pendingRecovery()).entries, isEmpty);
    } finally {
      other.dispose();
    }
  }
}

/// Every kind of step and variant the seeds must reach between them, so a
/// change to the generator can't quietly stop exercising one.
const _expectedKinds = {
  'edit:plain', 'edit:syncAtPublish', 'edit:syncBeforeWrite', 'edit:externalBeforeFlush',
  'edit:failOnce', 'edit:failAlways', //
  'external', 'rename:plain', 'rename:syncAtPublish', 'rename:syncBeforeWrite',
  'conflict:plain', 'conflict:replacedMidMerge', 'conflict:originalChanged',
  'conflict:stealPublish', 'conflict:scan', //
  'move:plain', 'move:pendingEdit', 'move:failDestination', 'move:failSourceDelete',
  'move:syncAtSource', //
  'delete:undo', 'delete:keep', 'delete:syncAtDelete', 'delete:failDelete', //
  'vanish:live/plain', 'vanish:restart/plain', 'vanish:live/syncWhileAway',
  'vanish:restart/syncWhileAway', 'vanish:live/deletedWhileAway',
  'vanish:restart/deletedWhileAway', 'vanish:live/replayFails',
  'vanish:restart/replayFails', 'restart', //
};

/// Run the parked probes too: --dart-define=RELOAD_PARKED=true.
const bool _runParked = bool.fromEnvironment('RELOAD_PARKED');

final Set<String> _seen = {};
int _started = 0;

void main() {
  Future<void> sequence(int seed) async {
    _started++;
    final run = _Run(seed);
    try {
      await run.start();
      for (var i = 1; i <= _steps; i++) {
        await run.step(i);
      }
      await run.nb.flush();
      await run.verify('end', fresh: true);
      if (const bool.fromEnvironment('RELOAD_TRACE')) debugPrint(run.trace.join('\n'));
    } finally {
      _seen.addAll(run.kinds);
      await run.stop();
    }
  }

  for (final seed in _seeds) {
    test(
      'seed $seed: the files and a fresh notebook equal the model',
      () => sequence(seed),
      timeout: const Timeout(Duration(minutes: 3)),
    );
  }
  for (var i = 0; i < _extraSeeds; i++) {
    final seed = 1000 + i;
    test(
      'long run, seed $seed',
      () => sequence(seed),
      timeout: const Timeout(Duration(minutes: 3)),
    );
  }

  test('the seeds reach every kind of step', () {
    if (_started < _seeds.length + _extraSeeds) {
      markTestSkipped('only some of the seeds ran (a filtered run)');
      return;
    }
    final missing = _expectedKinds.difference(_seen);
    expect(missing, isEmpty, reason: 'steps the seeds never made (reached: $_seen)');
  });

  group('probes of the faults on their own', () {
    late _Run run;
    setUp(() async {
      run = _Run(900);
      await run.start();
    });
    tearDown(() => run.stop());

    test(
      'a publish that keeps failing, then leaving the page: the edit is not lost',
      () async {
        final id = run.model.keys.first;
        final m = run.model[id]!;
        await run.nb.open(id);
        run._addBox(m, run.nb.current!);
        run.storeOf(m.loc).publishFailures = 50;
        await run.nb.flush();
        run.storeOf(m.loc).publishFailures = 0;
        // The user goes to another page, and quits.
        await run.nb.open(run.model.keys.last);
        await run.nb.flush();
        run._drop();
        await run._verifyDisk('after leaving');
      },
      skip: _runParked
          ? null
          : 'Found by D6: a write error that is not a missing folder is only logged. The edit stays '
                'on the screen but is in no file and no recovery entry, so leaving the page or quitting '
                'loses it. Minimal seed: any page, one added box, a failing publish, then open another page.',
    );

    // Run 2026-11-04-02, R-1 (area-data-integrity-2): Move attachments to
    // folder with the good copy unwritable keeps the embedded data, and puts
    // nothing hash-named into recovery (it would later land over the file).
    for (final recoveryToo in [true, false]) {
      test(
        'moving an embedded file to the folder when its copy cannot be stored keeps it embedded '
        '(recovery ${recoveryToo ? 'read-only' : 'writable'})',
        () async {
          final id = run.model.keys.first;
          final m = run.model[id]!;
          final data = Uint8List.fromList(List.generate(200, (i) => (i * 7) % 251));
          final name = attachmentFileName(contentHash(data), 'bin');
          await run.nb.open(id);
          await run.nb.setAttachmentStorage(id, AttachmentStorage.embedded);
          final made = await const FileModule().createFromFile(IncomingFile('f.bin', data), run.nb.attachments!);
          const codec = FileCodec();
          final box = commitBox(createBox(codec, const Bounds(5, 5, 200, 40)), codec, made!.$1);
          run.nb.current!.insertBox(box);
          await run.nb.flush();
          // A sync client has put the first bytes of the file in the folder.
          final assets = Directory('${run.dirs[m.loc]!.path}${run.sep}${assetsFolderName(id)}')..createSync();
          File('${assets.path}${run.sep}$name').writeAsBytesSync(data.sublist(0, 3));
          attachmentBeforeCreateHook = (path) {
            final inRec = path.replaceAll('\\', '/').contains('/rec');
            if (path.contains('.assets') && (recoveryToo || !inRec)) throw const FileSystemException('injected');
          };
          addTearDown(() => attachmentBeforeCreateHook = null);
