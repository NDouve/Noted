  BoxRecord _newBox(String text) {
    final codec = modules.codecs.codecFor('noted.note')!;
    final id = ((seed * 100000 + ++_boxCounter) + 0x1000000000000000).toRadixString(16);
    final at = Bounds(10.0 + 20 * (_boxCounter % 20), 10.0 + 40 * (_boxCounter % 13), 200, 40);
    return commitBox(createBox(codec, at).withId(id), codec, codec.decode(_doc(text), 1));
  }

  String _text(String what) => '$what s$seed.$_boxCounter';

  void _addBox(_MPage m, CanvasController c) {
    final b = _newBox(_text('local'));
    c.insertBox(b);
    m.boxes[b.id] = _val(b);
  }

  /// A local edit on the open page [c]: adds, retexts or deletes a box.
  void _localEdit(_MPage m, CanvasController c, {bool addOnly = false}) {
    final k = addOnly || m.boxes.isEmpty ? 0 : rng.nextInt(10);
    if (k < 6) {
      _addBox(m, c);
    } else if (k < 9) {
      final id = m.boxes.keys.elementAt(rng.nextInt(m.boxes.length));
      final codec = modules.codecs.codecFor('noted.note')!;
      final text = _text('edited');
      c.editBox(id, codec.decode(_doc(text), 1));
      m.boxes[id] = (text: text, bounds: m.boxes[id]!.bounds);
    } else {
      final id = m.boxes.keys.elementAt(rng.nextInt(m.boxes.length));
      c.delete(id);
      m.boxes.remove(id);
    }
  }

  // -- reading the world ------------------------------------------------------

  String _pathOf(String id, [String? loc]) => '${dirs[loc ?? model[id]!.loc]!.path}$sep$id.canvas';

  NotedPage _disk(String id, [String? loc]) => readPage(File(_pathOf(id, loc)).readAsStringSync());

  /// A sync client writing [page] over the page's file, atomically.
  Future<void> _externalWrite(String id, NotedPage page) =>
      _busyRetry(() => PageStore(dirs[model[id]!.loc]!).save(page));

  /// The same, from inside a hook (synchronous; the file is absent or replaced
  /// at that moment, so nothing else could be reading it).
  void _externalWriteSync(String id, NotedPage page) =>
      File(_pathOf(id)).writeAsStringSync(writePage(page));

  String _pick(List<String> items) => items[rng.nextInt(items.length)];

  String _pickPage({bool Function(String id, _MPage m)? where}) {
    final ids = [
      for (final e in model.entries)
        if (where == null || where(e.key, e.value)) e.key,
    ];
    return ids[rng.nextInt(ids.length)];
  }

  // -- the steps --------------------------------------------------------------

  Future<void> step(int n) async {
    try {
      await _step(n);
    } on TestFailure catch (e) {
      if ((e.message ?? '').contains('trace of seed')) rethrow;
      throw TestFailure('${e.message}\n--- trace of seed $seed ---\n${trace.join('\n')}');
    }
  }

  Future<void> _step(int n) async {
    _kind = null;
    final r = rng.nextInt(100);
    final String name;
    if (r < 16) {
      name = 'edit';
      await _opEdit();
    } else if (r < 26) {
      name = 'external';
      await _opExternal();
    } else if (r < 35) {
      name = 'copy';
      await _opCopy();
    } else if (r < 44) {
      name = 'move';
      await _opMove();
    } else if (r < 53) {
      name = 'delete';
      await _opDelete();
    } else if (r < 59) {
      name = 'rename';
      await _opRename();
    } else if (r < 69) {
      name = 'vanish';
      await _opVanish();
    } else if (r < 73) {
      name = 'restart';
      await _opRestart();
    } else {
      name = 'trouble';
      await _opTrouble();
    }
    trace.add('  ($name done)');
    await _settle();
    await verify('step $n ($name)');
    if (_kind != null) kinds.add(_kind!);
    // Another device's binders come and go beside the step (a generator of
    // its own, so the sequences of the steps above are the ones they were).
    if (_brng.nextInt(100) < 35) await _binderStep();
    // A replayed page is overwritten right after it lands (a generator of its
    // own too).
    if (_orng.nextInt(100) < 15) await _recoverStep(n);
    // A landed page is moved into a folder that holds an entry of it (own generator).
    if (_lrng.nextInt(100) < 15) await _landedMovedStep(n);
    // A box is brought to front or sent to back (a generator of its own, after
    // the others, so their traces stay the ones they were).
    if (_yrng.nextInt(100) < 15) await _layerStep(n);
  }

  /// The step `recover:overwrittenAfterLanding` after step [n], on pages picked
  /// by its own generator.
  Future<void> _recoverStep(int n) async {
    final withBox = [
      for (final e in model.entries)
        if (e.value.boxes.isNotEmpty) e.key,
    ];
    if (withBox.isEmpty || model.length < 2) return;
    final id = withBox[_orng.nextInt(withBox.length)];
    final others = [
      for (final i in model.keys)
        if (i != id) i,
    ];
    final other = others[_orng.nextInt(others.length)];
    trace.add('recover:overwrittenAfterLanding on ${_short(id)}');
    final ran = await _recoverOverwritten(id, other);
    trace.add('  ($ran done)');
    await _settle();
    await verify('step $n ($ran)');
    if (ran != null) kinds.add(ran);
  }

  /// How often each variant of [_layerStep] was started, over all sequences:
  /// the least tried goes next, so every variant is reached.
  static final Map<String, int> _layerTried = {};

  static const _layerVariants = ['local', 'externalOnly', 'both', 'undo', 'vanish'];

  /// The step `layer:<variant>` after step [n]: a box is brought to the front
  /// or sent to the back of a page that has at least three note boxes, on a
  /// page picked by its own generator (and a variant picked from the least
  /// tried).
  Future<void> _layerStep(int n) async {
    final pages = [
      for (final e in model.entries)
        if (e.value.boxes.length >= 3) e.key,
    ];
    if (pages.isEmpty) return;
    final sorted = [..._layerVariants]..shuffle(_yrng);
    sorted.sort((a, b) => (_layerTried[a] ?? 0).compareTo(_layerTried[b] ?? 0));
    final variant = sorted.first;
    final id = pages[_yrng.nextInt(pages.length)];
    final ran = await _layer(id, variant);
    if (ran == null) return;
    _layerTried[variant] = (_layerTried[variant] ?? 0) + 1;
    trace.add('  ($ran done)');
    await _settle();
    await verify('step $n ($ran)');
    kinds.add(ran);
  }

  /// The ids of the note boxes of [page] in its order.
  List<String> _noteOrder(NotedPage page, _MPage m) => [
    for (final n in page.nodes)
      if (m.boxes.containsKey(n.id)) n.id,
  ];

  /// A box of [page] that [move] would change, picked by the layer generator,
  /// or null.
  String? _stackable(NotedPage page, _MPage m, StackMove move) {
    final ids = [
      for (final n in page.nodes)
        if (m.boxes.containsKey(n.id) && stackTarget(page, n.id, move) != null) n.id,
    ];
    return ids.isEmpty ? null : ids[_yrng.nextInt(ids.length)];
  }

  /// [order] with [x] at the end (front) or the start (back).
  List<String> _moved(List<String> order, String x, StackMove move) => [
    if (move == StackMove.back) x,
    for (final i in order)
      if (i != x) i,
    if (move == StackMove.front) x,
  ];

  /// Runs layer step [variant] on page [id]; returns its kind, or null if no
  /// box could be moved.
  Future<String?> _layer(String id, String variant) async {
    final m = model[id]!;
    if (variant == 'vanish' && m.loc != 'x' && m.loc != 'a') return null;
    final move = _yrng.nextBool() ? StackMove.front : StackMove.back;
    trace.add('layer:$variant ${move.name} on ${_short(id)} in ${m.loc}');
    await nb.open(id);
    final c = nb.current!;
    final before = _noteOrder(c.page, m);
    final x = _stackable(c.page, m, move);
    if (x == null) return null;
    final mine = _moved(before, x, move);
    final st = storeOf(m.loc);
    switch (variant) {
      case 'local':
        expect(c.restack(x, move), isTrue);
        await nb.flush();
        m.order = mine;
      case 'externalOnly':
        // Another writer reorders the file and nothing local changed since the
        // last save: theirs' order is taken.
        final theirs = _disk(id);
        final y = _stackable(theirs, m, move);
        if (y == null) return null;
        await _externalWrite(id, theirs.moveNode(y, stackTarget(theirs, y, move)!));
        await nb.checkFile(_pathOf(id)); // the watcher's event
        m.order = _moved(_noteOrder(theirs, m), y, move);
      case 'both':
        // A local reorder; at its write another writer's reorder (and a box of
        // its own) is in the file: this side's order of the shared boxes wins,
        // the other side's box is kept.
        expect(c.restack(x, move), isTrue);
        final theirs = _disk(id);
        final y = _newBox(_text('sync'));
        // Theirs puts the first note box on top, whatever mine did.
        final first = _noteOrder(theirs, m).first;
        final next = theirs.moveNode(first, theirs.nodes.length - 1);
        var fired = false;
        st.beforeWrite = () {
          fired = true;
          _externalWriteSync(id, next.insertNode(y));
        };
        await nb.flush();
        expect(fired, isTrue, reason: 'the sync writer never got its turn');
        m.boxes[y.id] = _val(y);
        m.order = mine;
      case 'undo':
        expect(c.restack(x, move), isTrue);
        await nb.flush();
        c.undo();
        await nb.flush();
        m.order = before;
      case 'vanish':
        // The folder goes away, the reorder is kept in recovery and replayed.
        expect(c.restack(x, move), isTrue);
        final dir = dirs[m.loc]!;
        final awayDir = '${dir.path}-away';
        await _busyRetry(() async => dir.renameSync(awayDir));
        await nb.flush();
        expect((await nb.pendingRecovery()).entries.map((e) => e.pageId), [
          id,
        ], reason: 'the reorder was not kept for recovery');
        await nb.checkFolders(); // notices the folder is gone
        await _busyRetry(() async => Directory(awayDir).renameSync(dir.path));
        await nb.checkFolders();
        expect((await nb.pendingRecovery()).entries, isEmpty, reason: 'the entry was not replayed');
        m.order = mine;
    }
    return 'layer:$variant';
  }

  /// The step `recover:landedMovedIntoEntry` after step [n], on a page picked
  /// by its own generator.
  Future<void> _landedMovedStep(int n) async {
    final tops = [
      for (final e in model.entries)
        if (e.value.parent == null && _subtree(e.key).length == 1) e.key,
    ];
    if (tops.isEmpty || model.length < 2) return;
    final id = tops[_lrng.nextInt(tops.length)];
    final tos = [
      for (final l in _locs)
        if (l != model[id]!.loc) l,
    ];
    final to = tos[_lrng.nextInt(tos.length)];
    trace.add('recover:landedMovedIntoEntry on ${_short(id)} to $to');
    final ran = await _recoverLandedMoved(id, to);
    trace.add('  ($ran done)');
    await _settle();
    await verify('step $n ($ran)');
    if (ran != null) kinds.add(ran);
  }

  // An entry of closed page [id] adds box y1 and lands, but its settling fails
  // once, so the landed text is kept. Then an entry for the page is written
  // under the target [to], adding y2, after the landing: a replay with both in
  // place would take it for a stale key of the page and merge it into the
  // source first. The page is moved to [to] and replayed again: the page there
  // must hold y1 and y2, and no entry is left. The model gets both boxes (the
  // move itself changes the page's placement).
  Future<String?> _recoverLandedMoved(String id, String to) async {
    final m = model[id]!;
    if (_standaloneLeft([id], to: to) < 1) return null;
    await nb.open(_pickPage(where: (i, p) => i != id));
    final y1 = _newBox(_text('landed'));
    final y2 = _newBox(_text('target'));
    await _entryFor(id, y1);
    final prev = nb.syncHook;
    var failed = false;
    nb.syncHook = (point, path) async {
      await prev?.call(point, path);
      if (point != 'recover-published' || !path.endsWith('$id.canvas') || failed) return;
      failed = true;
      throw const FileSystemException('injected failure while settling');
    };
    try {
      await nb.recoverNowForTest();
    } finally {
      nb.syncHook = prev;
    }
    expect(failed, isTrue, reason: 'the entry landed and its settling failed');
    // Written after the landing, so the replay above did not merge it into the
    // source (the stale key goes first).
    final text = File(_pathOf(id)).readAsStringSync();
    await RecoveryStore(rec).write(
      folder: dirs[to]!.path,
      page: readPage(text).insertNode(y2),
      baseText: text,
      time: DateTime.now(),
    );
    await nb.refreshRecoveryIndexForTest();
    m.boxes[y1.id] = _val(y1);
    m.boxes[y2.id] = _val(y2);
    Object? error;
    try {
      await _moveTo(id, to);
    } on Object catch (e) {
      error = e;
    }
    expect(error, anyOf(isNull, isA<NotebookException>()), reason: 'the move failed: $error');
    if (error == null) {
      m.loc = to;
      m.parent = null;
    }
    await _replayAll();
    return 'recover:landedMovedIntoEntry';
  }

  /// The watcher's job: look at every conflict copy (and set-aside file) left
  /// in the folders until none is left, or give up after a few rounds.
  Future<void> _settle() async {
    for (var round = 0; round < 6; round++) {
      final copies = <String>[];
      for (final loc in _locs) {
        final d = dirs[loc]!;
        if (!d.existsSync()) continue;
        for (final f in d.listSync()) {
          if (f is! File) continue;
          final name = f.path.split(RegExp(r'[\\/]')).last;
          if (name.endsWith('.canvas') && !_isPageFile(name)) copies.add(f.path);
        }
      }
      if (copies.isEmpty) break;
      for (final c in copies) {
        await nb.checkFile(c);
      }
    }
  }

  /// How many standalone pages (default folder, second folder) the model has
  /// once [moving] go to [to] (null: they are gone).
  int _standaloneLeft(List<String> moving, {required String? to}) {
    final standalone = (to == null || to == 'pages' || to == 'x');
    var n = 0;
    for (final e in model.entries) {
      final isStandalone = e.value.loc == 'pages' || e.value.loc == 'x';
      if (moving.contains(e.key)) {
        if (standalone && to != null) n++;
      } else if (isStandalone) {
        n++;
      }
    }
    return n;
  }

  bool _isPageFile(String name) =>
      model.keys.any((id) => name == '$id.canvas') || name == binderFileName;

  // ---- edit: a save of the open page, sometimes raced or failed ---------------

  Future<void> _opEdit() async {
    final id = _pickPage();
    final m = model[id]!;
    final variant = _pick([
      'plain',
      'plain',
      'plain',
      'syncAtPublish',
      'syncBeforeWrite',
      'externalBeforeFlush',
      'failOnce',
      'failAlways',
    ]);
    trace.add('edit ${_short(id)} in ${m.loc}: $variant');
    _kind = 'edit:$variant';
    await nb.open(id);
    final c = nb.current!;
    final st = storeOf(m.loc);
    final racing = variant == 'syncAtPublish' || variant == 'syncBeforeWrite';
    _localEdit(m, c, addOnly: racing || variant == 'externalBeforeFlush');
    switch (variant) {
      case 'plain':
        await nb.flush();
      case 'syncAtPublish':
      case 'syncBeforeWrite':
        // The sync client's version, made from the file as it is now, with a
        // box of its own.
        final y = _newBox(_text('sync'));
        final base = _disk(id);
        var fired = false;
        void hook() {
          fired = true;
          _externalWriteSync(id, base.insertNode(y));
        }

        if (variant == 'syncAtPublish') {
          st.beforePublishOnce = hook;
        } else {
          st.beforeWrite = hook;
        }
        await nb.flush();
        expect(fired, isTrue, reason: 'the sync writer never got its turn');
        m.boxes[y.id] = _val(y);
      case 'externalBeforeFlush':
        // The file changes and no watcher event has run yet.
        final y = _newBox(_text('sync'));
        await _externalWrite(id, _disk(id).insertNode(y));
        await nb.flush();
        m.boxes[y.id] = _val(y);
      case 'failOnce':
        // One failed publish: the replace tries again.
        st.publishFailures = 1;
        await nb.flush();
        expect(st.publishFailures, 0);
      case 'failAlways':
        // The publish keeps failing: the file is put back as it was and the
        // edit stays on the screen. The user types on and the next save lands
        // everything.
        st.publishFailures = 50;
        await nb.flush();
        st.publishFailures = 0;
        _addBox(m, c);
        await nb.flush();
    }
  }

  // ---- trouble: failed saves, kept edits, previews, moves and deletes of kept pages (R-1 v5)

  /// How often each variant of [_opTrouble] was started, over all sequences:
  /// the least tried goes next, so every variant is reached.
  static final Map<String, int> _tried = {};

  static const _troubleVariants = [
    'edit:failIoStay',
    'edit:failIoLeave',
    'edit:failIoReopenPreview',
    'edit:stallLeave',
    'edit:previewDeleteRetire',
    'edit:failBothCancelLeave',
    'edit:discardAfterEntry',
    'replay:hangDuringLeave',
    'reopen:entryThenFailIo',
    'recovery:listFails',
    'ai:vanishWithEntry',
    'move:withEntry',
    'move:withEntryCrash',
    'move:withEntrySourceDeleteFails',
    'move:withEntryPartialRollback',
    'move:withEntryFolderGone',
    'move:withEntryRekeyFails',
    'move:withEntrySettleFails',
    'delete:withEntry',
    'delete:withEntryAsk',
    'launch:pageInBothKeys',
    'launch:pageInNeither',
  ];

  Future<void> _opTrouble() async {
    final sorted = [..._troubleVariants]..shuffle(rng);
    sorted.sort((a, b) => (_tried[a] ?? 0).compareTo(_tried[b] ?? 0));
    final variant = sorted.first;
    trace.add('trouble $variant');
    // The page the scenario is about, and a page elsewhere to go to.
    final ids = model.keys.toList();
    final id = ids[rng.nextInt(ids.length)];
    final m = model[id]!;
    String? otherIn(bool Function(String id, _MPage p) where) {
      final c = [for (final e in model.entries) if (e.key != id && where(e.key, e.value)) e.key];
      return c.isEmpty ? null : c[rng.nextInt(c.length)];
    }

    // Another page in another folder (a hung folder holds its own lock).
    final elsewhere = otherIn((i, p) => p.loc != m.loc);
    final any = otherIn((i, p) => true);
    if (any == null) return;
    String? ran;
    switch (variant) {
      case 'edit:failIoStay':
        ran = await _editFailStay(id);
      case 'edit:failIoLeave':
        ran = await _editFailLeave(id, any);
      case 'edit:failIoReopenPreview':
        ran = await _editFailPreview(id, any);
      case 'edit:stallLeave':
        if (elsewhere != null) ran = await _editStallLeave(id, elsewhere);
      case 'edit:previewDeleteRetire':
        ran = await _editPreviewDelete(id, any);
      case 'edit:failBothCancelLeave':
        ran = await _editFailBoth(id, any);
      case 'edit:discardAfterEntry':
        ran = await _editDiscard(id);
      case 'replay:hangDuringLeave':
        final third = otherIn((i, p) => i != any && p.loc != m.loc);
        final inThird = third == null ? null : otherIn((i, p) => i != third && p.loc != model[third]!.loc && p.loc != m.loc);
        if (elsewhere != null && third != null && inThird != null) {
          ran = await _replayHang(id, elsewhere, third, inThird);
        }
      case 'reopen:entryThenFailIo':
        ran = await _reopenEntry(id, any, listFails: false);
      case 'recovery:listFails':
        ran = await _reopenEntry(id, any, listFails: true);
      case 'ai:vanishWithEntry':
        ran = await _aiVanish();
      case 'move:withEntry':
      case 'move:withEntryCrash':
      case 'move:withEntrySourceDeleteFails':
      case 'move:withEntryPartialRollback':
      case 'move:withEntryFolderGone':
      case 'move:withEntryRekeyFails':
      case 'move:withEntrySettleFails':
        ran = await _moveWithEntry(variant, id, any);
      case 'delete:withEntry':
      case 'delete:withEntryAsk':
        ran = await _deleteWithEntry(variant, id, any);
      case 'launch:pageInBothKeys':
        ran = await _launchBothKeys(id);
      case 'launch:pageInNeither':
        ran = await _launchNeither();
    }
    if (ran != null) {
      _kind = ran;
      _tried[variant] = (_tried[variant] ?? 0) + 1;
    }
  }

  // The open page is [id], with a local edit made.
  Future<CanvasController> _openEdit(String id, {bool addOnly = false}) async {
    await nb.open(id);
    final c = nb.current!;
    _localEdit(model[id]!, c, addOnly: addOnly);
    return c;
  }

  /// A recovery entry for page [id] that adds [y] to the file as it is, written
  /// the way an earlier session left it.
  Future<RecoveryEntry> _entryFor(String id, BoxRecord y) async {
    final m = model[id]!;
    final text = File(_pathOf(id)).readAsStringSync();
    final e = await RecoveryStore(rec).write(
      folder: dirs[m.loc]!.path,
      page: readPage(text).insertNode(y),
      baseText: text,
      time: DateTime.now(),
    );
    await nb.refreshRecoveryIndexForTest();
    return e;
  }

  Future<void> _replayAll() async {
    await nb.recoverNowForTest();
    await _until(() => nb.recoveryStoreForTest!.indexEntries.isEmpty, 'the entries to be replayed');
  }

  // An entry edits a box of closed page [id]; another writer replaces the file
  // with their own version of that box right after the replay's publish
  // (0130). The edit is not lost and not silently replaced: the file shows
  // their version with the entry's recorded as a conflict, in the live
  // notebook and in a fresh one, and no entry or notice is left. The step then
  // keeps the displayed version, as the user would, so the model stays free of
  // conflicts. Null (not run) when the page has no note box.
  Future<String?> _recoverOverwritten(String id, String other) async {
    final m = model[id]!;
    if (m.boxes.isEmpty) return null;
    final target = m.boxes.keys.first;
    await nb.open(other);
    final codec = modules.codecs.codecFor('noted.note')!;
    final text = File(_pathOf(id)).readAsStringSync();
    final page = readPage(text);
    final old = page.node(target)! as BoxRecord;
    final mineText = _text('mine');
    final theirsText = _text('theirs');
    final mine = commitBox(old, codec, codec.decode(_doc(mineText), 1));
    final theirs = commitBox(old, codec, codec.decode(_doc(theirsText), 1));
    await RecoveryStore(rec).write(
      folder: dirs[m.loc]!.path,
      page: page.replaceNode(mine),
      baseText: text,
      time: DateTime.now(),
    );
    await nb.refreshRecoveryIndexForTest();
    final prev = nb.syncHook;
    nb.syncHook = (point, path) async {
      await prev?.call(point, path);
      if (point != 'recover-published' || !path.endsWith('$id.canvas')) return;
      final f = File(path);
      f.writeAsStringSync(writePage(readPage(f.readAsStringSync()).replaceNode(theirs)));
    };
    try {
      await _replayAll();
    } finally {
      nb.syncHook = prev;
    }
    void expectBothVersions(Notebook n, String where) {
      final box = _disk(id).node(target)! as BoxRecord;
      expect(_textOf(box), theirsText, reason: '$where: their version stays displayed');
      expect(box.conflicts, hasLength(1), reason: '$where: the entry\'s version is recorded');
      expect(_textOf(BoxRecord.tryRead(RawObject.parse(box.conflicts.single.node!.text), box.conflicts.single.node!)!), mineText,
          reason: '$where: the recorded version is the entry\'s');
      expect(n.hasConflict(id), isTrue, reason: '$where: the page shows the conflict');
      expect(n.recoveryProblems, isEmpty, reason: '$where: no notice, the conflict is the indication');
    }

    expectBothVersions(nb, 'live');
    _drop();
    nb = _make();
    _spare.add(nb);
    await nb.load();
    expectBothVersions(nb, 'after a restart');
    expect((await nb.pendingRecovery()).entries, isEmpty);

    // The user keeps the displayed version.
    await nb.open(id);
    nb.current!.resolveKeepMine(target);
    await nb.flush();
    m.boxes[target] = (text: theirsText, bounds: m.boxes[target]!.bounds);
    await nb.open(other);
    return 'recover:overwrittenAfterLanding';
  }

  /// Waits until [done]; [what] is the text of what it waits for, or a function
  /// that makes it when the wait fails (to say what the state was then).
  Future<void> _until(bool Function() done, Object what) async {
    final end = DateTime.now().add(const Duration(seconds: 10));
    while (!done()) {
      if (DateTime.now().isAfter(end)) {
        fail('seed $seed: timed out waiting for ${what is String Function() ? what() : what}');
      }
      await Future<void>.delayed(const Duration(milliseconds: 10));
    }
  }

  /// Retry on the preview of page [id], and then the page open for editing.
  ///
  /// The notebook's own backoff replays kept changes on a clock of its own. A
  /// Retry does nothing while the page is busy with such a replay, and a
  /// Retry that lands the changes can return while the other one is still
  /// reopening the page. So this waits for the page to be free before it
  /// retries, and then for the state Retry is meant to reach, rather than
  /// assuming nothing else is running.
  Future<void> _retryPreview(String id) async {
    await _until(() => !nb.isBusy(id), 'a background replay of the page to end');
    // The page was free, so this Retry replays the kept changes itself (nothing
    // can start between the check above and the call). Its work must have
    // landed: a background replay that merely cleared the preview in the
    // meantime does not stand in for it.
    final retried = nb.trouble.kind == TroubleKind.preview;
    await nb.retryPreview();
    if (retried) {
      expect(
        nb.recoveryStoreForTest!.indexEntries.where((e) => e.pageId == id),
        isEmpty,
        reason: 'Retry replayed the kept changes of the page',
      );
    }
    await _until(
      () => nb.current?.page.id == id && !nb.trouble.isTrouble && !nb.current!.readOnly,
      () =>
          'the page to be open for editing after Retry (trouble ${nb.trouble.kind}, '
          'busy: ${nb.isBusy(id)}, open: ${nb.currentId == id}, read-only: ${nb.current?.readOnly})',
    );
  }

