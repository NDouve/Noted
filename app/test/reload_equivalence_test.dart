  Future<void> _verifyDisk(String where) async {
    for (final loc in _locs) {
      final d = dirs[loc]!;
      final expected = <String>{
        if (loc == 'a' || loc == 'b') binderFileName,
        for (final e in model.entries)
          if (e.value.loc == loc) '${e.key}.canvas',
        for (final e in model.entries)
          if (e.value.loc == loc && e.value.assetText != null) assetsFolderName(e.key),
        for (final (l, id) in leftFolders)
          if (l == loc) assetsFolderName(id),
      };
      final actual = <String>{for (final f in d.listSync()) f.path.split(RegExp(r'[\\/]')).last};
      expect(actual, expected, reason: '$where: the files in $loc');
    }
    for (final e in asides.entries) {
      expect(File(e.key).readAsBytesSync(), e.value, reason: '$where: the kept file ${e.key}');
    }
    for (final e in model.entries) {
      final id = e.key;
      final m = e.value;
      final page = _disk(id);
      if (m.hashFile) {
        expect(File(_hashPath(id)).readAsBytesSync(), _goodBytes, reason: '$where: the hash file of page ${_short(id)}');
      }
      if (m.assetText != null) {
        expect(
          File('${dirs[m.loc]!.path}$sep${assetsFolderName(id)}${sep}a.txt').readAsStringSync(),
          m.assetText,
          reason: '$where: the attachment of page ${_short(id)}',
        );
      }
      expect(
        _boxesOf(page, '$where: ${_short(id)} on disk'),
        m.boxes,
        reason: '$where: boxes of page ${_short(id)} in ${m.loc}',
      );
      expect(m.orderIn(page), m.wantOrder, reason: '$where: stacking order of page ${_short(id)} on disk');
      expect(page.meta.title, m.title, reason: '$where: title of ${_short(id)}');
      expect(page.meta.parentId, m.parent, reason: '$where: parent of ${_short(id)}');
    }
  }

  Future<void> _verifyLive(String where) async {
    final recov = await nb.pendingRecovery();
    expect(recov.entries, isEmpty, reason: '$where: recovery entries are pending');
    expect(recov.problems, isEmpty, reason: '$where: recovery problems');
    expect(nb.recoveryDamaged, isEmpty, reason: '$where: recovery damage');
    expect(nb.unreadable, isEmpty, reason: '$where: unreadable files');
    for (final b in nb.binders) {
      expect(b.unreadable, isEmpty, reason: '$where: unreadable files in ${b.path}');
    }
    expect(nb.unsavedDescription, isNull, reason: '$where: unsaved work');
    final c = nb.current;
    if (c != null && model.containsKey(c.page.id)) {
      final m = model[c.page.id]!;
      expect(_boxesOf(c.page, '$where: the open page'), m.boxes, reason: '$where: the open page');
      expect(m.orderIn(c.page), m.wantOrder, reason: '$where: stacking order of the open page');
    }
    for (final e in model.entries) {
      final want = e.value.loc == 'a' ? pathA : (e.value.loc == 'b' ? pathB : null);
      expect(nb.binderOfPage(e.key), want, reason: '$where: binder of ${_short(e.key)}');
    }
  }

  Future<void> _verifyFresh(String where) async {
    final other = Notebook(
      PageStore(dirs['pages']!),
      modules,
      saveDelay: const Duration(hours: 1),
      bindersFile: settings,
      recoveryDirectory: rec,
      folderCheckInterval: Duration.zero,
      readOnlyRoots: pullOnly ? [root.path] : const [],
    );
    _spare.add(other);
    _gone.add(other);
    await other.load();
    await _verifyBinders(where, other);
    try {
      for (final e in model.entries) {
        expect(
          other.treeOfPage(e.key)[e.key],
          isNotNull,
          reason: '$where: a fresh notebook does not list ${_short(e.key)}',
        );
        final want = e.value.loc == 'a' ? pathA : (e.value.loc == 'b' ? pathB : null);
        expect(other.binderOfPage(e.key), want, reason: '$where: fresh binder of ${_short(e.key)}');
        await other.open(e.key);
        expect(
          _boxesOf(other.current!.page, '$where: fresh ${_short(e.key)}'),
          e.value.boxes,
          reason: '$where: a fresh notebook shows page ${_short(e.key)} differently',
        );
        expect(other.current!.page.meta.title, e.value.title);
        expect(
          e.value.orderIn(other.current!.page),
          e.value.wantOrder,
          reason: '$where: a fresh notebook stacks page ${_short(e.key)} differently',
        );
      }
      final listed = <String>{
        ...other.tree.roots.expand((r) => [r.id, ...other.tree.descendantsOf(r.id)]),
        for (final b in other.binders)
          ...b.tree.roots.expand((r) => [r.id, ...b.tree.descendantsOf(r.id)]),
      };
      expect(listed, model.keys.toSet(), reason: '$where: the pages a fresh notebook lists');
      expect((await other.pendingRecovery()).entries, isEmpty);
    } finally {
      other.dispose();
    }
  }
