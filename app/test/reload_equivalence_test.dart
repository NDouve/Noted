  // ---- copy: a sync client's conflict copy appears ----------------------------

  Future<void> _opCopy() async {
    final id = _pickPage();
    final m = model[id]!;
    final variant = _pick([
      'plain',
      'plain',
      'replacedMidMerge',
      'originalChanged',
      'stealPublish',
      'scan',
    ]);
    trace.add('conflict copy of ${_short(id)} in ${m.loc}: $variant');
    _kind = 'conflict:$variant';
    // The merge hooks belong to the closed-page merge: close the page.
    if (variant == 'replacedMidMerge' || variant == 'originalChanged') {
      await nb.open(_pickPage(where: (i, p) => i != id));
    }
    final disk = _disk(id);
    final z = _newBox(_text('copy'));
    final path = '${dirs[m.loc]!.path}$sep$id-DESKTOP-${++_copyCounter}.canvas';
    if (variant == 'stealPublish') {
      if (m.boxes.isEmpty) {
        _kind = null;
        return;
      }
      // R-3 as it happens in a run: the copy and the other device's newer file
      // both lack a box the original has, and the other device's file lands at
      // the publish. The original's own box must survive.
      await nb.open(_pickPage(where: (i, p) => i != id));
      final a = m.boxes.keys.elementAt(rng.nextInt(m.boxes.length));
      final without = disk.removeNode(a);
      final w = _newBox(_text('newer'));
      File(path).writeAsStringSync(writePage(without.insertNode(z)));
      storeOf(m.loc).beforePublishOnce = () => _externalWriteSync(id, without.insertNode(w));
      await nb.checkFile(path);
      await _settle();
      m.boxes[z.id] = _val(z);
      m.boxes[w.id] = _val(w);
      return;
    }
    File(path).writeAsStringSync(writePage(disk.insertNode(z)));
    m.boxes[z.id] = _val(z);
    switch (variant) {
      case 'plain':
        await nb.checkFile(path);
      case 'scan':
        await nb.checkFolders();
      case 'replacedMidMerge':
        // The provider replaces the copy with a newer one while it is merged.
        final later = _newBox(_text('later'));
        var fired = false;
        nb.syncHook = (point, p) async {
          if (point != 'copy-merged' || fired) return;
          fired = true;
          File(path).writeAsStringSync(writePage(disk.insertNode(z).insertNode(later)));
        };
        await nb.checkFile(path);
        nb.syncHook = null;
        expect(fired, isTrue);
        m.boxes[later.id] = _val(later);
      case 'originalChanged':
        // The other device's edit lands on the original after it was read.
        final newer = _newBox(_text('newer'));
        var fired = false;
        nb.syncHook = (point, p) async {
          if (point != 'original-read' || fired) return;
          fired = true;
          await _busyRetry(() => PageStore(dirs[m.loc]!).save(disk.insertNode(newer)));
        };
        await nb.checkFile(path);
        nb.syncHook = null;
        expect(fired, isTrue);
        m.boxes[newer.id] = _val(newer);
    }
  }

